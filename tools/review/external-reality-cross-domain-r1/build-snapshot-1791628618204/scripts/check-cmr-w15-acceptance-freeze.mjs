import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
const root=process.cwd(); const base='content/professional/canonical-meaning-runtime';
const j=async p=>JSON.parse(await fs.readFile(path.join(root,p),'utf8'));
const sha=async p=>crypto.createHash('sha256').update(await fs.readFile(path.join(root,p))).digest('hex');
const acceptance=await j(`${base}/acceptance/cmr-w15-full-acceptance-v1.json`);
const freeze=await j(`${base}/freeze/cmr-w15-full-freeze-v1.json`);
const w14Contract=await j(`${base}/contracts/meaning-projection-for-journey-contract-v1.json`);
const w14Acceptance=await j(`${base}/acceptance/cmr-w14-journey-meaning-projection-acceptance-v1.json`);
const w14Freeze=await j(`${base}/freeze/cmr-w14-journey-meaning-projection-freeze-v1.json`);
const reconciliation=await j(`${base}/contracts/cmr-w13-w14-reconciliation-contract-v1.json`);
const w13Acceptance=await j(`${base}/acceptance/cmr-w13-meaning-knowledge-bridge-acceptance-v1.json`);
assert.equal(acceptance.status,'accepted_validation_only');
assert.equal(acceptance.productionStatus,'validation_only');
assert.equal(acceptance.acceptanceVersion,'1.0.1');
assert.equal(freeze.status,'CMR Frozen v1');
assert.equal(freeze.productionStatus,'validation_only');
assert.equal(freeze.productionActivated,false);
assert.equal(freeze.paidJourneyActivated,false);
assert.equal(freeze.successorRequiredForActivation,true);
assert.equal(freeze.w14Status,'frozen_v1_preserved');
assert.equal(freeze.w14LiveCMW13Integration,false);
assert.equal(freeze.futureW14SuccessorRequiredForLiveCMW13Integration,true);
// W13 now exists and is independently accepted.
assert.equal(w13Acceptance.status,'passed_validation_only');
assert.equal(reconciliation.rules.cmW13Available,true);
// W14 v1 historical truth is preserved exactly: it was frozen before W13 and performs no live query.
assert.equal(w14Contract.knowledgeBoundary.cmW13MeaningToKnowledgeBridgePresent,false);
assert.equal(w14Contract.knowledgeBoundary.knowledgeQueryAllowed,false);
assert.equal(w14Contract.knowledgeBoundary.futureCMW13IntegrationRequiresVersionedSuccessor,true);
assert.equal(w14Acceptance.upstreamStatus.cmW13Available,false);
assert.equal(w14Acceptance.upstreamStatus.cmW14DependsOnCMW13ForCurrentVersion,false);
assert.equal(w14Acceptance.upstreamStatus.cmW14KnowledgeCoverageMode,'inherited_bundle_summary');
for (const file of w14Freeze.outputs) assert.equal(await sha(file),w14Freeze.digests[file],`W14 frozen digest ${file}`);
assert.equal(acceptance.reconciliation.cmW13AvailableAtW15,true);
assert.equal(acceptance.reconciliation.historicalW14StatementIsPreservedNotRewritten,true);
assert.equal(acceptance.reconciliation.cmW14V1PerformsLiveCMW13Query,false);
assert.equal(acceptance.reconciliation.futureLiveCMW13IntegrationRequiresVersionedCMW14Successor,true);
for (const [p,d] of Object.entries(acceptance.artifactDigests)) assert.equal(await sha(p),d,`artifact digest ${p}`);
for (const [p,d] of Object.entries(freeze.protectedBaselineDigests)) assert.equal(await sha(p),d,`protected digest ${p}`);
assert.equal(await sha(`${base}/acceptance/cmr-w15-full-acceptance-v1.json`),freeze.acceptanceDigest);
const forbidden=JSON.stringify(acceptance);
assert.doesNotMatch(forbidden,/productionStatus"\s*:\s*"active"|paidJourneyActivated"\s*:\s*true/i);
console.log('✓ CM-W15 CMR Full Acceptance and Freeze reconciliation passed.');
console.log('✓ CM-W13 is available independently while frozen CM-W14 v1 remains no-query and historically intact.');
console.log('✓ Live CM-W13 → Journey integration requires a versioned CM-W14 successor; CMR remains validation_only.');
