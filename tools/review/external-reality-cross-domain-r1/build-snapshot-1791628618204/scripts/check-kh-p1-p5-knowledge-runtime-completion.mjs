import assert from 'node:assert/strict';
import fs from 'node:fs/promises';import path from 'node:path';
import {createKnowledgeCompletionRuntime} from '../functions/knowledge-runtime/knowledge-completion-runtime.js';
const root=process.cwd();const j=async f=>JSON.parse(await fs.readFile(path.join(root,f),'utf8'));
const books=await j('content/knowledge/completion/book-completion-registry-v1.json');
const coverage=await j('content/knowledge/completion/canonical-node-coverage-v1.json');
const priority=await j('content/knowledge/completion/priority-knowledge-production-v1.json');
const expansion=await j('content/knowledge/completion/published-fragment-expansion-v1.json');
const freeze=await j('content/knowledge/completion/knowledge-runtime-production-freeze-v1.json');
const nodes=await j('content/knowledge/registry/nodes.json');
const publishedNodes=await j('content/knowledge/public/published-nodes.json');
const publishedArticles=await j('content/knowledge/public/published-articles.json');
const fragments=await j('content/knowledge/public/retrieval/fragments.json');
assert.equal(books.books.length,4);assert.equal(books.books[0].manuscript_complete,true);assert.equal(books.books[1].drafting,true);
assert.equal(coverage.canonicalNodeCount,716);assert.equal(coverage.records.length,nodes.nodes.length);assert.equal(coverage.summary.nodeExists,716);
assert.equal(priority.pilotNodeCount,32);assert.ok(priority.pilotNodeCount>=20&&priority.pilotNodeCount<=40);assert.equal(new Set(priority.nodes.map(n=>n.nodeCode)).size,32);
assert.equal(expansion.records.length,32);assert.equal(freeze.boundaries.queryRuntimeReadOnly,true);assert.equal(freeze.boundaries.productionCoveragePromotionAllowed,false);
assert.equal(freeze.currentCoverage.publishedNodeLocaleRecords,publishedNodes.recordCount);assert.equal(freeze.currentCoverage.publishedArticleLocaleRecords,publishedArticles.recordCount);assert.equal(freeze.currentCoverage.publishedFragments,fragments.recordCount);
const runtime=createKnowledgeCompletionRuntime({root});
const known=coverage.records.find(r=>r.hasPublishedFragment);assert.ok(known);
assert.equal(runtime.coverageQuery({nodeCode:known.nodeCode}).status,'found');
const locale=known.localeCoverage[0];assert.equal(runtime.publishedOnlyQuery({nodeCode:known.nodeCode,locale}).status,'covered');
assert.equal(runtime.publishedOnlyQuery({nodeCode:'KN-B4-P15-071',locale:'en'}).status,'coverage_gap');
assert.ok(['covered','gap'].includes(runtime.assemblyQuery({nodeCode:known.nodeCode,locale}).status));
assert.equal(runtime.priorityQueue().length,32);assert.equal(runtime.bookCompletion().length,4);
console.log('✓ KH-P1 Book Completion Registry passed.');
console.log('✓ KH-P2 Canonical Node Coverage passed: 716 nodes remain distinct from real coverage.');
console.log('✓ KH-P3 Priority Knowledge Production passed: 32 governed pilot nodes.');
console.log('✓ KH-P4 Published Fragment Expansion passed without fabricated coverage.');
console.log('✓ KH-P5 Knowledge Runtime Production Freeze passed: five read-only query contracts.');
