import assert from 'node:assert/strict';
import fs from 'node:fs';
import {resolveExplicitAskContexts,buildAskContextAvailability} from '../functions/contextual-ask/contextual-ask-runtime.js';
const read=p=>fs.readFileSync(p,'utf8');
const json=p=>JSON.parse(read(p));
const c=json('content/customer-experience-rebuild/cx-r31/contracts/cx-r31-w2-progressive-explicit-context-v1.json');
const html=read('knowledge/ask/index.html');
const client=read('assets/customer-ui/js/surfaces/contextual-ask.js');
assert.equal(c.status,'COMPLETE');
assert.deepEqual(c.defaultState.using,['KNOWLEDGE']);
assert.equal(c.defaultState.addContextCollapsed,true);
assert.equal(c.noSilentAccountSweep,true);
assert.equal(c.predecessorBoundaryPreserved,true);
for(const marker of ['data-cx-add-context','>Add context<','Using: Knowledge','data-cx-ask-context-selector','data-cx-current-reality-fields'])assert.ok(html.includes(marker),`progressive context UI missing ${marker}`);
assert.equal(/<details[^>]*data-cx-add-context[^>]*\sopen(?:\s|>)/.test(html),false,'Add context must be collapsed by default');
const defaultResolved=resolveExplicitAskContexts({requested:[{contextType:'KNOWLEDGE'}],resolvedContexts:[{contextType:'RELATIONSHIP_GOVERNED_READING',contextRef:'REL-SECRET',serverAuthorized:true,consent:{accepted:true}}],locale:'en'});
assert.deepEqual(defaultResolved.map(x=>x.contextType),['KNOWLEDGE'],'server-resolved account context was silently consumed');
const availability=buildAskContextAvailability({locale:'en'});
assert.deepEqual(availability.map(x=>x.contextType),['KNOWLEDGE','CURRENT_REALITY']);
assert.ok(client.includes("contextConsent:{CURRENT_REALITY:form.elements.currentRealityConsent.checked===true}"),'explicit current reality consent not preserved');
console.log('✓ CX-R31-W2 Progressive + Explicit Context passed: Knowledge default, Add context collapsed, no silent account sweep.');
