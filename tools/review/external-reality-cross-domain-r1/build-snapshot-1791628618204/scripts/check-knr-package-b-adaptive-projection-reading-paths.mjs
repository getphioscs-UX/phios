import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { buildAdaptiveProjection, buildPublishedReadingPath, runPackageB } from './lib/knowledge-runtime/knr-package-b-v1.mjs';
import { sha } from './lib/knowledge-runtime/knr-package-a-v1.mjs';
const root = process.cwd();
const read = async file => JSON.parse(await fs.readFile(path.join(root, file), 'utf8'));
const contract = await read('content/knowledge/contracts/knr-package-b-adaptive-projection-reading-paths-v1.json');
assert.equal(contract.policies.publishedOnly, true);
assert.equal(contract.policies.providerFree, true);
assert.equal(contract.policies.verbatimFragmentsOnly, true);
assert.equal(contract.prohibitedOperations.includes('generate_answer'), true);
const exact1 = await runPackageB('人工智能如何从文明能力中形成？', 'zh-Hans', 'auto');
const exact2 = await runPackageB('人工智能如何从文明能力中形成？', 'zh-Hans', 'auto');
assert.deepEqual(exact1, exact2);
assert.equal(exact1.projection.node.nodeCode, 'KN-PREFACE-001');
assert.equal(exact1.projection.answerGenerated, false);
assert.equal(exact1.projection.textRewritten, false);
assert(exact1.projection.fragments.length >= 1);
const sourceFragments = await read('content/knowledge/public/retrieval/fragments.json');
for (const fragment of exact1.projection.fragments) {
  const source = sourceFragments.records.find(item => item.fragmentCode === fragment.fragmentCode);
  assert(source);
  assert.equal(fragment.text, source.text);
  assert.equal(fragment.digest, source.digest);
}
const full = await buildAdaptiveProjection({ query: '完整文章', locale: 'zh-Hans', mode: 'auto' });
assert.equal(full.mode, 'full_article');
assert.equal(full.fragments.length, sourceFragments.records.filter(item => item.nodeCode === 'KN-PREFACE-001' && item.locale === 'zh-Hans').length);
const overview = await buildAdaptiveProjection({ query: '人工智能概览', locale: 'zh-Hans', mode: 'auto' });
assert.equal(overview.mode, 'overview');
assert(overview.fragments.length < full.fragments.length);
const en = await runPackageB('How does artificial intelligence emerge from civilization?', 'en', 'focused');
assert.equal(en.locale, 'en');
assert(en.projection.fragments.every(fragment => sourceFragments.records.some(item => item.fragmentCode === fragment.fragmentCode && item.locale === 'en')));
const pathResult = await buildPublishedReadingPath({ query: '人工智能如何从文明能力中形成？', locale: 'zh-Hans' });
assert.equal(pathResult.entryNodeCode, 'KN-PREFACE-001');
assert.equal(pathResult.steps[0].stepType, 'article');
assert(pathResult.steps.some(step => step.stepType === 'locale_switch' && step.locale === 'en'));
assert(pathResult.blockedContinuations.some(item => item.targetNodeCode === 'KN-PREFACE-002'));
assert.equal(pathResult.steps.some(step => step.nodeCode === 'KN-PREFACE-002'), false);
const none = await runPackageB('quantum banana submarine', 'en', 'auto');
assert.equal(none.projection.projectionCode, 'KNR-PROJECTION-NO-COVERAGE');
assert.equal(none.readingPath.steps.length, 0);
const unsupported = await runPackageB('anything', 'fr', 'auto');
assert.equal(unsupported.projection.fragments.length, 0);
const freeze = await read('content/knowledge/production/freeze/knr-package-b-adaptive-projection-reading-paths-v1.json');
const index = await read('content/knowledge/public/retrieval/published-retrieval-index.json');
assert.equal(freeze.status, 'KNR-PACKAGE-B-v1.0.0-Frozen');
assert.equal(freeze.sourceIndexDigest, index.indexDigest);
assert.equal(freeze.contractDigest, sha(contract));
console.log('✓ KNR-W6 deterministic Adaptive Projection passed.');
console.log('✓ KNR-W7 published-only Reading Paths and locale switch passed.');
console.log('✓ Unpublished continuation remains disclosed but non-navigable.');
console.log('✓ No Provider, answer generation, translation, rewriting or canonical mutation passed.');
