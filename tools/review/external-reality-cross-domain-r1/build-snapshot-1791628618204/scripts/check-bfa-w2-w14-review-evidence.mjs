import assert from 'node:assert/strict';
import fs from 'node:fs';
import { projectPjaBrief, buildAuthoringPrompt, buildFigureAuthoringBrief, runAutomaticPreflight, validateFigureRequirement } from './lib/bilingual-final-approval/bfa-runtime-v1.mjs';
import { readCarResult } from './lib/bilingual-final-approval/bfa-batch-builder-v1.mjs';
const root=process.cwd();
const contract=JSON.parse(fs.readFileSync(`${root}/content/production/bilingual-final-approval/contracts/bfa-review-evidence-and-projection-contract-v1.json`,'utf8'));
assert.equal(contract.pjaBriefProjection.htmlMayInterpretCanonicalMeaning,false);
assert.equal(contract.candidateIntake.candidateOnly,true);
assert.deepEqual(contract.automaticPreflight.statuses,['PASS','WARNING','BLOCKED']);
assert.equal(contract.figure.nullAllowed,false);
assert.equal(contract.figure.carAuthorityMayBeCreatedByBfa,false);
const brief=JSON.parse(fs.readFileSync(`${root}/content/knowledge/production/briefs/zh-Hans/KN-B1-P2-009-production-brief.v2.json`,'utf8'));
const projection=projectPjaBrief(brief,{figureRequirement:{state:'FIGURE_NOT_REQUIRED',reason:'fixture'}});
assert.equal(projection.canonicalMeaning,brief.canonicalMeaning.centralThesis);
assert.equal(projection.authority.mayCreateMeaning,false);
assert.ok(buildAuthoringPrompt(projection,'en').promptDigest.match(/^[a-f0-9]{64}$/));
const figureBrief=buildFigureAuthoringBrief(projection);
for(const field of ['figurePurpose','canonicalConceptsRepresented','requiredRelationships','mustShow','mustNotImply','visualHierarchy','textPolicy','localePolicy','altIntent','recommendedPlacement','aspectRatio','surface','sourceDigest']) assert.ok(Object.hasOwn(figureBrief,field),`W7 Figure Production Brief missing ${field}`);
assert.equal(figureBrief.authority,'PJA_CAR_INTERFACE_PROJECTION_ONLY');
const car=readCarResult(root,'KN-PREFACE-001');
assert.equal(car?.candidate?.nodeCode,'KN-PREFACE-001');
assert.equal(car?.review?.decision,'accept');
assert.equal(car?.approval?.decision,'approved');
assert.equal(car?.media?.rightsStatus,'cleared');
assert.ok(car?.published?.publicationDigest);
assert.equal(validateFigureRequirement({state:'FIGURE_NOT_REQUIRED',reason:''}).valid,false);
const c=JSON.parse(fs.readFileSync(`${root}/content/knowledge/production/candidates/zh-Hans/KN-B1-P2-009/candidate.v1.json`,'utf8'));
const evidence=runAutomaticPreflight({projection,candidate:c,locale:'zh-Hans',sameRouteIdentity:{canonicalRoute:'/articles/projection-bias-distortion-stability-and-renewal',locales:['zh-Hans','en']},figure:{state:'FIGURE_NOT_REQUIRED',reason:'The canonical concept is adequately expressed without a visual projection.'},presentationPreview:{sourceDigest:'a'.repeat(64)}});
assert.ok(['PASS','WARNING','BLOCKED'].includes(evidence.status));
assert.equal(evidence.authority.humanAcceptance,false);
console.log('✓ BFA-W2～W14 review projection, Candidate intake, automatic evidence, Figure/CAR boundary and CPR preview contracts passed.');
console.log('✓ Review UI is projection-only; Automatic PASS remains evidence and can never become TL approval.');
console.log('✓ Figure null is forbidden; FIGURE_NOT_REQUIRED needs an explicit reason and required CAR remains fail-closed.');
