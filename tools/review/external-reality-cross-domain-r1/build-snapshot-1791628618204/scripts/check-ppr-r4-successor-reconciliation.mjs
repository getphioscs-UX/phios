import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {assertPprC1CurrentSuccessor} from './lib/ppr-c1-current-successor.mjs';
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const {r4,current,r5,historicalPostR4Proof}=assertPprC1CurrentSuccessor();
const path='perspectives/personal/index.html';
const proof=historicalPostR4Proof(path);
assert(proof,'PPR-R4 current-main index successor proof missing');
assert.equal(r4.sharedFileSuccessorProof[path].successorSha256,'e7babe088b63fe8266787ed855726b7dfd3969b6e3c1a3854a509e07ba245376');
assert.equal(proof.predecessorSha256,r4.sharedFileSuccessorProof[path].successorSha256);
assert.equal(proof.successorSha256,'45ce923352d91dca8d7b3d3cc4dde47b70234ce6fad684b35b34b4e34d52d33e');
assert.equal(proof.currentGitBlobSha,'414616b072bfde18094e5b3555489d76478ca494');
assert.equal(proof.changeClass,'ECR_SCOPED_STYLESHEET_LINK_ONLY');
assert.equal(current.boundaries.historicalPprR4FreezeMutated,false);
assert.equal(current.boundaries.historicalEcrW19RecordMutated,false);
assert.equal(current.boundaries.sharedPprRendererSemanticsChanged,false);
assert(r5,'PPR-R5 editorial successor authority missing');
assert.equal(r5.sharedFileSuccessorProof[path].predecessorSha256,proof.successorSha256);
assert.equal(r5.sharedFileSuccessorProof[path].successorSha256,sha(path));
assert.equal(r5.sharedFileSuccessorProof[path].changeClass,'PPR_R5_EDITORIAL_SURFACE_SUCCESSOR');
console.log('✓ PPR-R4 current-main successor digest reconciliation passed.');
console.log('  PPR-R4 index successor e7babe… → current 45ce923… is exactly one admitted ECR scoped stylesheet link.');
console.log('  Historical PPR-R4 and ECR W19 records remain immutable; PPR-R5 is a later editorial-only page successor.');
