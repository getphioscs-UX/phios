import assert from 'node:assert/strict';
import {buildPersonalEvidenceRealityHandoff,selectPersonalEvidenceHandoffReferences} from '../functions/profile/personal-evidence-handoffs.js';
import {buildCurrentRealityBundle} from '../functions/reality-orchestration/reality-orchestrator.js';
const card={signalRef:'SOURCE-A',sourceClass:'STANDARDIZED_SELF_REPORT',providerFamily:'IPIP',assessmentDate:'2026-10-04',domainId:'BIG_FIVE::OPENNESS',value:{rawMean:3},provenance:[{source:'RESULT-A'}],precisionBoundary:['NOT_DIAGNOSIS'],unknownState:'OPEN'};
const view={schemaVersion:'PHI-OS-PROGRESSIVE-PROFILE-VIEW-v1',participantRef:'PERSON-A',profileViewId:'VIEW-A',signalCards:[card,{...card,signalRef:'SOURCE-B'}]};
const handoff=buildPersonalEvidenceRealityHandoff({profileView:view,selectedEvidenceRefs:['SOURCE-A'],openQuestion:'Does this resonate now?'});
const selected=selectPersonalEvidenceHandoffReferences({...handoff,evidenceReferences:[...handoff.evidenceReferences,{sourceId:'UNSELECTED',sourceClass:'EXTERNAL_PROFILE_RESULT'}]});
assert.equal(selected.length,1);
assert.deepEqual(selected[0].nativeValue,card.value);
assert.deepEqual(selected[0].provenance,card.provenance);
assert.deepEqual(selected[0].precisionBoundary,card.precisionBoundary);
assert.equal(selected[0].unknownState,'OPEN');
assert.throws(()=>selectPersonalEvidenceHandoffReferences({...handoff,selectedEvidenceRefs:['MISSING']}),/SELECTION_MISMATCH/);
assert.throws(()=>selectPersonalEvidenceHandoffReferences({...handoff,automaticPersistence:true}),/SELECTION_REQUIRED/);
assert.throws(()=>buildPersonalEvidenceRealityHandoff({profileView:view,selectedEvidenceRefs:[]}),/EXPLICIT_SELECTION_REQUIRED/);
const bundle=await buildCurrentRealityBundle({sourceType:'PERSONAL_RUNTIME',source:{evidenceReferences:selected,unknown:[handoff.openQuestion]}});
const ref=bundle.lanes.externalEvidence[0];
for(const key of ['sourceClass','providerFamily','assessmentDate','nativeValue','provenance','precisionBoundary','unknownState'])assert.deepEqual(ref[key],selected[0][key]);
assert.equal(ref.realityFact,false);
assert.equal(bundle.governance.persisted,false);
// Exercise the actual API consent and malformed-selection gates after bundling its dependencies.
const {build}=await import('esbuild');
const fs=await import('node:fs');
const out='.tmp/prd-w7-api-test.mjs';
await build({entryPoints:['functions/api/customer-reality-handoff.js'],bundle:true,platform:'node',format:'esm',outfile:out,logLevel:'silent'});
const {onRequestPost}=await import('../'+out);
const call=body=>onRequestPost({request:new Request('https://fixture.invalid/api/customer-reality-handoff',{method:'POST',body:JSON.stringify(body)}),env:{}});
assert.equal((await call({sourceType:'PERSONAL_EVIDENCE',viewModel:handoff})).status,403);
assert.equal((await call({sourceType:'PERSONAL_EVIDENCE',viewModel:{...handoff,selectedEvidenceRefs:['MISSING']},consent:{explicit:true,accepted:true}})).status,400);
const accepted=await call({sourceType:'PERSONAL_EVIDENCE',viewModel:handoff,consent:{explicit:true,accepted:true}});
assert.equal(accepted.status,200);
assert.equal((await accepted.json()).continuation.persisted,false);
console.log('PRD_W7_PERSONAL_REALITY_HANDOFF = PASS');
