import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildAuthorizeUrl,assertLoopbackRedirect,pkceChallenge,sanitizeClientRegistration} from './lib/civilization-atlas/moomoo-pkce-auth-helper-v1.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=rel=>JSON.parse(fs.readFileSync(path.join(root,rel),'utf8'));
const text=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const ok=(v,c)=>{if(!v)throw new Error('MOOMOO_PKCE_AUTH_HELPER:'+c);};
const c=read('content/civilization-atlas/reconfiguration/moomoo-pkce-auth-helper-contract-v1.json');
ok(c.status==='EXECUTABLE_LOCAL_PKCE','CONTRACT');
ok(c.pkceMethod==='S256'&&c.redirectUri==='http://localhost:60355/callback','PKCE_REDIRECT');
ok(c.secretPersistence?.accessToken===false&&c.secretPersistence?.refreshToken===false&&c.secretPersistence?.codeVerifier===false,'SECRET_PERSISTENCE');
assertLoopbackRedirect(c.redirectUri);
ok(JSON.stringify(c.authorizeQueryParameters)===JSON.stringify(['client_id','code_challenge','code_challenge_method','redirect_uri','response_type','state']),'AUTHORIZE_EXACT_SIX');
const verifier='A'.repeat(64);
const challenge=pkceChallenge(verifier);
ok(challenge.length>=43&&challenge.length<=128,'CHALLENGE_LENGTH');
const u=buildAuthorizeUrl({clientId:'client-1',redirectUri:c.redirectUri,state:'state-1',codeChallenge:challenge});
ok(u.startsWith('https://webapi.moomoo.com/oauth2/authorize/confirm?'),'AUTHORIZE_ENDPOINT');
for(const q of ['client_id=client-1','code_challenge_method=S256','response_type=code','state=state-1'])ok(u.includes(q),'AUTHORIZE_QUERY_'+q);
ok(!u.includes('scope='),'AUTHORIZE_SCOPE_NOT_INJECTED');
const meta=sanitizeClientRegistration({client_id:'abc',client_id_issued_at:1,client_name:'x',redirect_uris:[c.redirectUri],pkce_required:true,registration_access_token:'DO_NOT_COPY'});
ok(meta.clientId==='abc'&&!JSON.stringify(meta).includes('DO_NOT_COPY'),'REGISTRATION_SECRET_STRIPPED');
const helper=text('scripts/run-moomoo-pkce-auth-helper.mjs');
for(const forbidden of ['console.log(token.access_token)','console.log(token.refresh_token)','registration_access_token:body.registration_access_token'])ok(!helper.includes(forbidden),'SECRET_LOG_OR_PERSIST_'+forbidden);
ok(helper.includes("server.listen(60355,'127.0.0.1')"),'LOOPBACK_BIND');
ok(helper.includes("await startCallbackServer(state)"),'LISTEN_BEFORE_BROWSER');
ok(helper.includes("WAITING_FOR_BROWSER_AUTHORIZATION"),'WAIT_STATE_VISIBLE');
ok(helper.includes("Start-Process -FilePath"),'WINDOWS_BROWSER_START_PROCESS');
ok(helper.includes("returnedState!==expectedState"),'STATE_VALIDATION');
ok(helper.includes("MOOMOO_ACCESS_TOKEN:accessToken"),'CHILD_ENV_HANDOFF');
ok(helper.includes("scripts/run-moomoo-first-live-import.mjs"),'LIVE_IMPORT_HANDOFF');
ok(!helper.includes('/trade/')&&!helper.includes('/account/'),'NO_TRADING_ACCOUNT_ENDPOINT');
const gi=text('.gitignore');ok(gi.includes('.moomoo-auth/'),'AUTH_DIR_GITIGNORED');
const pkg=text('package.json');ok(pkg.includes('"moomoo:pkce-live-import"')&&pkg.includes('"check:moomoo:pkce-auth"'),'PACKAGE');
console.log('PASS Moomoo PKCE auth helper: dynamic/local client_id, S256+state, loopback callback, in-memory token exchange, no token persistence, governed live-import child handoff.');
