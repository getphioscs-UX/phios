import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=rel=>JSON.parse(fs.readFileSync(path.join(root,rel),'utf8'));
const text=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const ok=(v,c)=>{if(!v)throw new Error('W8E_P2_GAP_CLOSURE:'+c);};
const gap=read('content/civilization-atlas/reconfiguration/runtime-position-w8e-p2-gap-closure-v1.json');
const plan=read('content/civilization-atlas/reconfiguration/moomoo-first-data-request-plan-v1.json');
const c=read('content/civilization-atlas/reconfiguration/runtime-position-w8e-p2-gap-closure-production-contract-v1.json');
ok(gap.status==='EXECUTABLE_GAP_CLOSURE_PLAN','GAP_STATUS');
ok((gap.targets||[]).length===3,'TARGET_COUNT');
ok((plan.gapClosureExecutableRequestIds||[]).length===4,'REQUEST_IDS');
const valuation=plan.requests.find(x=>x.capability==='VALUATION');ok((valuation.instruments||[]).every(x=>['US.AAPL','US.MSFT','US.AMZN','US.NVDA','US.JPM'].includes(x)),'VALUATION_STOCKS_ONLY');
ok(!valuation.instruments.some(x=>['US.SPY','US.QQQ','US.XLK','US.XLF','US.XLI','US.XLY','US.XLE','US.XLV'].includes(x)),'NO_ETF_VALUATION');
const cf=plan.requests.find(x=>x.capability==='CAPITAL_FLOW');ok((cf.instruments||[]).length===8,'CAPITAL_FLOW_ETF_UNIVERSE');
ok(plan.requests.some(x=>x.capability==='REVENUE_BREAKDOWN'),'REVENUE_BREAKDOWN_PLAN');
ok(c.boundaries?.tradingAllowed===false&&c.boundaries?.autoW8ePromotionAllowed===false,'BOUNDARY');
const importer=text('scripts/run-moomoo-gap-closure-import.mjs');
for(const endpoint of ['/capital-flow/history','/valuation/detail','/financials/statements','/financials/revenue-breakdown'])ok(importer.includes(endpoint),'ENDPOINT_'+endpoint);
ok(!/place-order|\/account\//i.test(importer),'NO_TRADING_ACCOUNT');
const helper=text('scripts/run-moomoo-pkce-auth-helper.mjs');ok(helper.includes("mode==='gap-closure'"),'PKCE_GAP_MODE');
const pkg=text('package.json');ok(pkg.includes('"moomoo:pkce-gap-closure"')&&pkg.includes('"check:runtime-position-48:w8e:p2:gap-closure"'),'PACKAGE');
console.log('PASS W8E-P2 gap closure: capital flow + stock valuation + financial statements + revenue breakdown are executable under quote/read OAuth; ETF valuation is blocked; no auto semantic promotion.');
