import assert from 'node:assert/strict';
import fs from 'node:fs';
import {resolveMandalaVisualState,resolveMandalaDriverRelation,ECR_MANDALA_PRIMARY_STORY_LAYERS,ECR_MANDALA_SECONDARY_DEPTH_LAYERS} from '../assets/customer-ui/js/specialists/ecr/mandala-hierarchy.js';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const contract=read('content/product-visual-platform-r1/ecr/hierarchy/ecr-mandala-hierarchy-contract-v1.json');
const acceptance=read('content/product-visual-platform-r1/acceptance/pvp-r1-vis-w11-ecr-mandala-hierarchy-v1.json');
const renderer=fs.readFileSync('assets/customer-ui/js/specialists/ecr/mandala-renderer.js','utf8');
const census=read('content/product-visual-platform-r1/ecr/census/ecr-mandala-visual-census-v1.json');
assert.equal(contract.status,'HIERARCHY_FROZEN_EXISTING_RENDERER_RECONCILED');
assert.deepEqual(contract.storyHierarchy.primaryStory,ECR_MANDALA_PRIMARY_STORY_LAYERS);
assert.deepEqual(contract.storyHierarchy.secondaryDepth,ECR_MANDALA_SECONDARY_DEPTH_LAYERS);
assert.deepEqual(census.canonicalLayerOrder,['CC12','G16','Q16','R9','D12','M8','H64','A8']);
assert.equal(resolveMandalaVisualState({layer:'CC12',selected:true,experienceState:'FREE_SNAPSHOT'}),'PRIMARY_ACTIVE');
assert.equal(resolveMandalaVisualState({layer:'R9',selected:true,relation:'PRIMARY',experienceState:'FREE_SNAPSHOT'}),'PRIMARY_ACTIVE');
assert.equal(resolveMandalaVisualState({layer:'R9',selected:true,relation:'SUPPORTING',experienceState:'FREE_SNAPSHOT'}),'LOCKED_DEPTH');
assert.equal(resolveMandalaVisualState({layer:'R9',selected:true,relation:'SUPPORTING',experienceState:'PAID_DEPTH'}),'SUPPORTING_ACTIVE');
assert.equal(resolveMandalaDriverRelation(1),'PRIMARY');
assert.equal(resolveMandalaDriverRelation(2),'SUPPORTING');
assert.equal(resolveMandalaDriverRelation(3),'SUPPORTING');
assert.equal(resolveMandalaVisualState({layer:'D12',driverRank:1,experienceState:'FREE_SNAPSHOT'}),'PRIMARY_ACTIVE');
assert.equal(resolveMandalaVisualState({layer:'D12',driverRank:2,experienceState:'FREE_SNAPSHOT'}),'LOCKED_DEPTH');
assert.equal(resolveMandalaVisualState({layer:'D12',driverRank:3,experienceState:'PAID_DEPTH'}),'SUPPORTING_ACTIVE');
assert.equal(resolveMandalaVisualState({layer:'D12',driverRank:4,experienceState:'PAID_DEPTH'}),'BACKGROUND');
for(const layer of ['M8','H64','A8']){
  assert.equal(resolveMandalaVisualState({layer,selected:true,experienceState:'FREE_SNAPSHOT'}),'LOCKED_DEPTH');
  assert.equal(resolveMandalaVisualState({layer,selected:true,experienceState:'PAID_DEPTH'}),'SUPPORTING_ACTIVE');
}
assert.match(renderer,/resolveMandalaVisualState/);
assert.match(renderer,/resolveMandalaDriverRelation/);
assert.match(renderer,/relation=resolveMandalaDriverRelation\(d\.rank\)/);
assert.equal(acceptance.status,'MACHINE_ACCEPTED_MANDALA_HIERARCHY');
assert.equal(acceptance.reconciliation.d12SupportingDriverGapClosed,true);
assert.equal(acceptance.assertions.w12AllowedNow,true);
assert.equal(contract.authorityBoundary.hierarchyMayChangeCalculation,false);
assert.equal(contract.authorityBoundary.hierarchyMayChangeSelectedCoordinate,false);
console.log('✓ PVP-R1-VIS-W11 Mandala Hierarchy passed.');
console.log('  Primary story: CC12 → G16 → Q16 → R9; secondary depth: D12 → M8 → H64 → A8.');
console.log('  D12 ranks 2–3 now resolve as supporting depth (paid) / locked depth (free); ranks 4–12 remain background.');
console.log('  No ECR calculation, semantic selection, geometry, or meaning authority changed.');
