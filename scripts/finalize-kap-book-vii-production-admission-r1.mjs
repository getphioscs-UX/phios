import fs from 'node:fs';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const root='content/knowledge/book-vii/production-admission';
const successor='content/knowledge/answer-projection/reconciliation/kap-book-vii-production-admission-successor-v1.json';
const hash=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const read=p=>JSON.parse(fs.readFileSync(p));
const validationPath=root+'/evidence/validation-summary-v1.json';
const validation=read(validationPath);
assert.equal(validation.status,'PRODUCTION_ADMITTED_LOCAL_VALIDATED');
assert.equal(validation.records.length,6);
assert.ok(validation.records.every(r=>r.exitCode===0));
assert.equal(validation.staticProjectionIncluded,true);
assert.equal(validation.privateLineageExcluded,true);
const doc=read(successor);
for(const entry of doc.changes)assert.equal(hash(entry.path),entry.successorSha256);
for(const entry of read(root+'/human-acceptance-v1.json').acceptedArtifacts)assert.equal(hash(entry.path),entry.sha256);
assert.equal(hash(doc.predecessorSuccessor),doc.predecessorSha256);
doc.status='PRODUCTION_ADMITTED_LOCAL_VALIDATED';
doc.validation={path:validationPath,sha256:hash(validationPath)};
doc.runtimeEvidence={path:root+'/evidence/runtime-admission-v1.json',sha256:hash(root+'/evidence/runtime-admission-v1.json')};
doc.addedRuntimeModules=[{path:'functions/_lib/book-vii-published-admission.js',sha256:hash('functions/_lib/book-vii-published-admission.js')}];
fs.writeFileSync(successor,JSON.stringify(doc,null,2)+'\n');
const review='tools/review/KAP-BOOK-VII-PRODUCTION-ADMISSION-R1-REVIEW.html';
const esc=s=>s.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;');
let html=fs.readFileSync(review,'utf8');
html=html.replace(/<section id="final-validation">[\s\S]*?<\/section>/,'');
html=html.replace('</html>','<section id="final-validation"><h2>Final admission validation</h2><pre>'+esc(JSON.stringify({...validation,publishedCommandProbes:validation.publishedCommandProbes.map(p=>({command:p.command,exitCode:p.exitCode,nodeCode:p.result.projection.node?.nodeCode}))},null,2))+'</pre><h2>Admission SHA successor</h2><pre>'+esc(JSON.stringify(doc,null,2))+'</pre></section></html>');
fs.writeFileSync(review,html);
const paths=[successor,review,'package.json','config/reports/zero-cost-check-commands.json','functions/_lib/book-vii-published-admission.js','scripts/admit-kap-book-vii-production-r1.mjs','scripts/check-kap-book-vii-admitted-current.mjs','scripts/check-kap-phase18-production-admission-current.mjs','scripts/check-kap-book-vii-production-admission.mjs','scripts/validate-kap-book-vii-production-admission-r1.mjs','scripts/finalize-kap-book-vii-production-admission-r1.mjs',root+'/human-acceptance-v1.json',root+'/README.md',doc.release.path,...doc.changes.map(e=>e.path)];
fs.writeFileSync(root+'/evidence/work-manifest-v1.json',JSON.stringify({work:doc.work,status:doc.status,liveDeploymentPerformed:false,scope:'Book VII additive admission only; unrelated Ziwei changes excluded',files:[...new Set(paths)].map(path=>({path,sha256:hash(path)}))},null,2)+'\n');
console.log('PASS production admission finalized: all six checks and three published CLI probes; private lineage excluded; accepted R1 SHA records preserved.');
