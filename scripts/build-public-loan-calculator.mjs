import {build} from 'esbuild';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
// Generated browser projection of the canonical calculator; no second formula owner.
export async function buildPublicLoanCalculator(){
 const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
 await build({stdin:{contents:"export {calculateLoan,validateToolScenarios} from './functions/financial/calculation-runtime/customer-finance-tools.js';",resolveDir:root},bundle:true,format:'esm',platform:'browser',target:'es2022',outfile:path.join(root,'assets/customer-ui/js/surfaces/loan-calculator.generated.js'),banner:{js:'// Generated by scripts/build-public-loan-calculator.mjs from the canonical financial calculation runtime.'}});
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildPublicLoanCalculator();
