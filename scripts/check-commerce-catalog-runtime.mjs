import assert from 'node:assert/strict';
import {commerceApi} from '../functions/commerce/commerce-stripe-api.js';
import {commerceProduct} from '../functions/pws/commercial/stripe-product-registry.js';
import {resolveReportProduct,quoteReportPresentation,requirePurchasedReportPresentation} from '../functions/pws/commercial/report-successor-contract.js';

const request=new Request('https://qa.phios-github.pages.dev/api/commerce-catalog',{method:'GET'});
const context={request,env:{STRIPE_ENVIRONMENT:'QA',PHIOS_COMMERCE_QA_ENABLED:'true',STRIPE_SECRET_KEY:'sk_test_placeholder'}};
const response=await commerceApi(context,'catalog');
assert.equal(response.status,200);
const body=await response.json();
assert.equal(body.success,true);
assert(Array.isArray(body.products));
assert(body.products.length>0);
const profile=body.products.find(p=>p.productId==='COM-REPORT-PROFILE-FULL');
assert.equal(profile,undefined,'Profile must stay outside the standalone catalog');
const historicalProfile=commerceProduct('COM-REPORT-PROFILE-FULL');
assert.equal(historicalProfile.catalogVisible,false);
assert.equal(historicalProfile.commercialState,'LEGACY_HISTORY_ONLY');
assert.equal(historicalProfile.checkoutBlockedReason,'PERSONAL_EVIDENCE_MEMBERSHIP_NOT_STANDALONE');
const contract=resolveReportProduct('PROFILE_FULL_REPORT');
assert.equal(contract.newPrimaryPromotion,false);assert.equal(contract.newPurchaseDefault,false);
const presentation={reportLanguageMode:'BILINGUAL',reportLocale:'bilingual'};
assert.throws(()=>quoteReportPresentation(contract.productId,presentation),/PWS_REPORT_LEGACY_NEW_PURCHASE_DISABLED/);
assert.deepEqual(requirePurchasedReportPresentation({entitlement_status:'active',purchase_id:'historical-profile-fixture',reportPresentation:presentation},presentation),presentation);
assert.throws(()=>requirePurchasedReportPresentation({entitlement_status:'inactive',purchase_id:'historical-profile-fixture',reportPresentation:presentation},presentation),error=>error.code==='REPORT_ENTITLEMENT_REQUIRED');
const ziwei=body.products.find(p=>p.productId==='COM-REPORT-ZIWEI-FULL');
assert(ziwei);
assert.equal(ziwei.reportPurchaseState,'AVAILABLE');
assert.equal(ziwei.reportPresentationOptions.length,3);
console.log('PASS commerce catalog: Profile is history-only and excluded from standalone sales; verified historical purchase presentation remains readable; current Zi Wei retains three language quotes.');
