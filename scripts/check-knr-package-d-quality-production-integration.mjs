import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {evaluatePublishedKnowledgeQuality,buildProductionIntegrationReport} from './lib/knowledge-runtime/knr-package-d-v1.mjs';
const root=process.cwd();
const json=async f=>JSON.parse(await fs.readFile(path.join(root,f),'utf8'));
const contract=await json('content/knowledge/contracts/knr-package-d-quality-production-integration-v1.json');
const qPolicy=await json('content/knowledge/runtime/knr/package-d/quality-evaluation-policy-v1.json');
const iPolicy=await json('content/knowledge/runtime/knr/package-d/production-integration-policy-v1.json');
assert.equal(contract.contractCode,'KNR-PACKAGE-D-QUALITY-PRODUCTION-INTEGRATION');
assert.equal(qPolicy.providerAllowed,false);assert.equal(qPolicy.automaticRepairAllowed,false);assert.equal(iPolicy.mode,'read_only_gate');
const a=await evaluatePublishedKnowledgeQuality(root);const b=await evaluatePublishedKnowledgeQuality(root);assert.deepEqual(a,b);assert.equal(a.reportDigest,b.reportDigest);
assert.equal(a.summary.publishedLocaleRecords,2);assert.equal(a.summary.publishedCanonicalNodes,1);
assert.equal(a.findings.some(x=>x.code==='EN_LOCALE_CJK_CONTAMINATION'),true);
assert.equal(a.findings.some(x=>x.code==='EN_HEADING_CJK_CONTAMINATION'),true);
assert.equal(a.findings.some(x=>x.code==='EN_BODY_CJK_CONTAMINATION'),true);
assert.equal(a.findings.some(x=>x.code==='ZH_SUMMARY_ARTIFACT_CONTAMINATION'),true);
assert.equal(a.summary.status,'blocked');
const integration=buildProductionIntegrationReport(a);assert.equal(integration.outcome,'blocked');
assert.deepEqual(integration.productionEffects,{candidateMutation:false,reviewMutation:false,approvalMutation:false,publicationMutation:false,registryMutation:false,automaticRepublish:false});
const forbidden=JSON.stringify({contract,qPolicy,iPolicy,integration});for(const token of ['provider_call','generated_answer','automatic_repair','automatic_republish'])assert.equal(forbidden.includes(`\"${token}\":true`),false);
console.log('✓ KNR-W10 deterministic Published Quality Evaluation passed.');
console.log('✓ English locale contamination and Chinese summary artifact contamination were detected and reported.');
console.log('✓ KNR-W11 read-only Production Integration gate passed.');
console.log('✓ No Candidate, Review, Approval, Publication or Registry mutation occurred.');
