import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const page=read('assets/js/pages/civilization-atlas.js');
const data=read('assets/js/pages/civilization-atlas/atlas-data.js');
const shell=read('assets/js/pages/civilization-atlas/atlas-shell.js');
const visual=read('assets/js/pages/civilization-atlas/atlas-structured-visual.js');

assert.ok(!page.includes('loadAtlasVisualProjection'),'W4A active page must not load poster projection manifest');
assert.ok(!data.includes('loadAtlasVisualProjection'),'W4A data loader must not require poster manifest');
assert.ok(!shell.includes('renderAtlasVisualProjection'),'W4A shell must not render poster projection');
assert.ok(!shell.includes('data-atlas-visual-projection'),'W4A shell must retire poster projection mount');
assert.ok(shell.includes('renderStructuredAtlasVisual'),'W4A structured visual mount missing');
assert.ok(shell.includes('data-atlas-structured-visual'),'W4A structured visual DOM mount missing');
assert.ok(visual.includes('<svg'),'W4A must provide SVG visualization');
assert.ok(visual.includes('data-structured-layer="timeline"'));
assert.ok(visual.includes('data-structured-layer="cases"'));
assert.ok(visual.includes('data-structured-layer="comparison"'));
assert.ok(visual.includes('data-structured-layer="world"'));
assert.ok(visual.includes('data-structured-layer="trajectories"'));
assert.ok(visual.includes('data-structured-layer="transitions"'));
assert.ok(visual.includes('data-structured-layer="loss"'));
assert.ok(visual.includes('EVIDENCE_SERIES')&&visual.includes('HISTORICAL_RECONSTRUCTION')&&visual.includes('CONCEPTUAL_TRAJECTORY'),'trajectory authority grammar missing');
assert.ok(!visual.includes('<img'),'W4A primary structured projection must not depend on raster posters');
assert.ok(!visual.includes('/images/atlas/'),'W4A must not depend on R2 Atlas image objects');
assert.ok(!page.includes('/images/atlas/')&&!shell.includes('/images/atlas/'),'active Atlas runtime still references R2 Atlas images');
for(const forbidden of ['civilizationScore','collapseScore','superiorityScore','overallWinner']) assert.ok(!visual.includes(forbidden),`forbidden ranking field: ${forbidden}`);
console.log('✓ BOOK-V-CIV-ATLAS-R1-M1-W4A Structured Dynamic Atlas Projection passed.');
console.log('  HTML/SVG is primary; Registry remains authority; R2 Atlas posters are no longer a runtime dependency.');
