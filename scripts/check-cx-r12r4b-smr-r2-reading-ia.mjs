import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildCustomerReadingIA} from '../functions/single-method-reading-r2/customer-reading-ia.js';
import {buildSyntheticR2Narrative} from './smr-r2-w9-w11-test-support.mjs';

const contract=JSON.parse(fs.readFileSync('content/customer-experience-rebuild/r12r4b/smr-r2/contracts/customer-reading-ia-v2.json','utf8'));
const schema=JSON.parse(fs.readFileSync('content/customer-experience-rebuild/r12r4b/smr-r2/contracts/customer-reading-ia-v2.schema.json','utf8'));
const registry=JSON.parse(fs.readFileSync('content/customer-experience-rebuild/r12r4b/smr-r2/registries/smr-r2-reading-section-registry-v2.json','utf8'));
assert.equal(contract.irSchemaVersion,'PHI-OS-CUSTOMER-READING-IA-v2.0.0');
assert.equal(contract.rules.customerReadingOrderOwnsBody,true);
assert.equal(contract.rules.methodObjectDirectoryOwnsBody,false);
assert.equal(contract.rules.emptyOptionalSectionsRender,false);
assert.equal(contract.rules.rendererMayCreateMeaning,false);
assert.equal(registry.methodDetail.defaultCollapsed,true);
const {narrative}=buildSyntheticR2Narrative();
const first=buildCustomerReadingIA({narrativeIR:narrative});
const second=buildCustomerReadingIA({narrativeIR:narrative});
assert.deepEqual(first,second);
assert.equal(first.schemaVersion,schema.properties.schemaVersion.const);
for(const key of schema.required)assert.ok(Object.prototype.hasOwnProperty.call(first,key));
assert.deepEqual(first.sections.map(item=>item.sectionId),contract.bodySectionOrder);
assert.deepEqual(first.sections.map(item=>item.order),[10,20,30,40,50,60,70,80]);
assert.equal(first.sections.find(item=>item.sectionId==='WHAT_STANDS_OUT').eligibility,'SECTION_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='YOUR_CORE_THEMES').eligibility,'SECTION_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='WHAT_SUPPORTS_YOU').eligibility,'SECTION_NOT_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='WHERE_TENSION_APPEARS').eligibility,'SECTION_NOT_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='WHEN_THE_PATTERN_CHANGES').eligibility,'SECTION_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='WHAT_THIS_MAY_LOOK_LIKE_IN_REALITY').eligibility,'SECTION_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='WHAT_TO_OBSERVE').eligibility,'SECTION_ELIGIBLE');
assert.equal(first.sections.find(item=>item.sectionId==='WHY_THIS_READING').disclosureLevel,'LEVEL_2_WHY_THIS_READING');
assert.equal(first.methodDetail.disclosureLevel,'LEVEL_3_TECHNICAL_DETAIL');
assert.equal(first.methodDetail.defaultCollapsed,true);
assert.equal(first.boundary.methodObjectDirectoryOwnsBody,false);
assert.equal(first.boundary.rendererMeaningCreated,false);
const narrativeTexts=new Set();
const visit=value=>{if(!value||typeof value!=='object')return;if(value.narrativeRef&&value.renderable&&value.text)narrativeTexts.add(value.text);for(const nested of Object.values(value))if(nested&&typeof nested==='object')visit(nested)};
visit(narrative);
for(const section of first.sections)for(const item of section.items){assert.equal(item.meaningCreated,false);if(item.text!==null)assert.ok(narrativeTexts.has(item.text),`IA introduced text outside Narrative IR: ${item.text}`)}
assert.ok(first.sections.every(item=>item.eligibility==='SECTION_ELIGIBLE'||item.itemCount===0));
console.log('✓ CX-R12R4B SMR-R2 W9 Reading IA passed: customer-order body, conditional section eligibility, three-level progressive disclosure and no method-object/technical takeover.');
