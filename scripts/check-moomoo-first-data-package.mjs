import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=rel=>JSON.parse(fs.readFileSync(path.join(root,rel),'utf8'));
const text=rel=>fs.readFileSync(path.join(root,rel),'utf8');
const ok=(v,c)=>{if(!v)throw new Error('MOOMOO_FIRST_DATA_PACKAGE:'+c);};
const c=read('content/civilization-atlas/reconfiguration/moomoo-first-data-package-contract-v1.json');
const p=read('content/civilization-atlas/reconfiguration/moomoo-first-data-request-plan-v1.json');
const t=read('content/civilization-atlas/reconfiguration/moomoo-first-data-import-template-v1.json');
const g=read('content/civilization-atlas/reconfiguration/moomoo-first-data-execution-guide-v1.json');
const w8b=read('content/civilization-atlas/reconfiguration/runtime-position-w8b-claim-extraction-contract-v1.json');
ok(c.status==='READY_AUTH_REQUIRED','CONTRACT');
ok(p.providerId==='MOOMOO_OPENAPI'&&p.liveCallPerformed===false,'PROVIDER_OR_LIVE');
ok((p.requests||[]).length===4,'REQUEST_FAMILY_COUNT');
ok(new Set(p.requests.map(x=>x.capability)).size===4,'REQUEST_CAPABILITY_UNIQUE');
ok((p.requests.find(x=>x.capability==='HISTORY_KLINE')?.instruments||[]).length===8,'HISTORY_UNIVERSE');
ok((p.requests.find(x=>x.capability==='FINANCIAL_STATEMENTS')?.instruments||[]).length===5,'FINANCIAL_UNIVERSE');
ok((p.requests||[]).every(x=>(x.gapTargets||[]).length>0),'GAP_TARGETS');
ok((c.forbidden||[]).includes('BUY_SELL_HOLD_RECOMMENDATION')&&(c.forbidden||[]).includes('TRADING_EXECUTION'),'NO_TRADING');
ok((w8b.allowedLocatorTypes||[]).includes('API_RESPONSE_FIELD')&&(w8b.allowedLocatorTypes||[]).includes('PROVIDER_SERIES_WINDOW'),'W8B_PROVIDER_LOCATORS');
ok(t.status==='EMPTY_TEMPLATE','IMPORT_TEMPLATE');
ok((g.stopConditions||[]).includes('SECRET_FOUND_IN_EXPORT'),'SECRET_STOP');
const pkg=text('package.json');ok(pkg.includes('"check:moomoo-first-data-package"'),'PACKAGE');
console.log('PASS first Moomoo data package: 4 governed request families, 8 market/sector instruments, 5 company financial pilots, no live call, no trading, W8B provider locators enabled.');
