import assert from 'node:assert/strict';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const base='content/customer-experience-rebuild'; const read=(p)=>JSON.parse(fs.readFileSync(p,'utf8'));
execFileSync(process.execPath,['scripts/generate-cx-r0-r1-r1a-successor.mjs','--check'],{stdio:'pipe'});
const registry=read(`${base}/legacy/legacy-customer-presentation-registry-v3.json`);
const css=read(`${base}/legacy/legacy-css-freeze-v2.json`);
const sig=read(`${base}/legacy/legacy-component-signature-registry-v2.json`);
const acceptance=read(`${base}/acceptance/cx-r1-acceptance-v2.json`);
assert.equal(registry.status,'LEGACY_PRESENTATION_QUARANTINED_AT_CURRENT_MAIN');
assert.ok(registry.summary.legacyActive>=100,'legacy/predecessor quarantine census unexpectedly small');
assert.ok(registry.summary.existingCxToReconcile>=8,'predecessor CX census unexpectedly small');
assert.ok(registry.legacy.every(x=>x.futureDesignAuthority===false&&x.physicalDeleteNow===false));
assert.ok(registry.predecessorCx.every(x=>x.futureSuccessorAuthority==='NOT_AUTOMATICALLY_GRANTED'));
assert.equal(css.status,'LEGACY_CSS_FROZEN_DEFECT_FIX_ONLY');
assert.ok(css.summary.frozenCustomerStylesheets>0);
assert.ok(css.entries.every(x=>x.futureCxImportAllowed===false&&x.defectFixOnly===true&&x.physicalDeleteAllowedNow===false));
assert.equal(sig.rules.renameAndCopyAllowed,false); assert.equal(sig.rules.compositionMigrationAllowed,false); assert.equal(sig.rules.semanticContentMigrationAllowed,true);
assert.deepEqual(acceptance.requiredExitStates,['LEGACY_PRESENTATION_QUARANTINED','NEW_CUSTOMER_SURFACES_CLEAN_ROOM_READY']);
assert.equal(acceptance.rules.physicalDeletePerformed,false); assert.equal(acceptance.rules.backendAuthorityTouched,false);
console.log(`✓ CX-R1 current quarantine passed: ${registry.summary.legacyActive} legacy/predecessor presentations frozen; ${registry.summary.existingCxToReconcile} existing CX surfaces explicitly require successor reconciliation.`);
console.log('✓ CX-R1 ACCEPTED: LEGACY_PRESENTATION_QUARANTINED · NEW_CUSTOMER_SURFACES_CLEAN_ROOM_READY');
