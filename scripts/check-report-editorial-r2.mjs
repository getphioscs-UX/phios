function dimensions(b){
 if(b.length>=24&&b.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])))return {width:b.readUInt32BE(16),height:b.readUInt32BE(20),encoding:'png'};
 if(b.toString('ascii',0,4)!=='RIFF'||b.toString('ascii',8,12)!=='WEBP')return null;
 for(let offset=12;offset+8<=b.length;){
  const type=b.toString('ascii',offset,offset+4),size=b.readUInt32LE(offset+4),at=offset+8;
  if(at+size>b.length)return null;
  if(type==='VP8X'&&size>=10)return {width:b.readUIntLE(at+4,3)+1,height:b.readUIntLE(at+7,3)+1};
  if(type==='VP8 '&&size>=10&&b.subarray(at+3,at+6).equals(Buffer.from([0x9d,0x01,0x2a])))return {width:b.readUInt16LE(at+6)&0x3fff,height:b.readUInt16LE(at+8)&0x3fff};
  if(type==='VP8L'&&size>=5&&b[at]===0x2f){const n=b.readUInt32LE(at+1);return {width:(n&0x3fff)+1,height:((n>>>14)&0x3fff)+1};}
  offset=at+size+(size%2);
 }
 return null;
}
