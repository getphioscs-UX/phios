import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import {ZIWEI_HUMAN_ADMITTED_CLAIM_IDS,assertZiweiSourceAdmission} from '../functions/zi-wei-full-production/ziwei-source-admission-authority-v1.js';
const j=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const base='content/professional/zi-wei-full-production/source-admission';
const extraction=j(`${base}/claims/ziwei-source-claim-batch-001-v1.json`);
const legacy=j(`${base}/registries/ziwei-source-admission-registry-v1.json`);
const reviewPath=`${base}/review/ziwei-source-claim-batch-001-human-review-result-v1.json`;
const review=j(reviewPath);
const admission=j(`${base}/admission/ziwei-source-claim-batch-001-admission-v1.json`);
const registry=j(`${base}/registries/ziwei-source-admission-registry-v2.json`);
const acceptance=j(`${base}/acceptance/ziwei-source-claim-batch-001-admission-acceptance-v1.json`);
assert.equal(review.schemaVersion,'PHI-OS-ZIWEI-SOURCE-CLAIM-HUMAN-REVIEW-RESULT-v1.0.0');
assert.equal(review.batchId,'ZIWEI-SOURCE-CLAIM-BATCH-001');
assert.equal(review.decisions.length,29);
assert.deepEqual(new Set(review.decisions.map(x=>x.decision)),new Set(['ADMIT']));
const claimIds=extraction.claims.map(x=>x.claimId);
assert.equal(new Set(claimIds).size,29);
assert.deepEqual(new Set(review.decisions.map(x=>x.claimId)),new Set(claimIds));
assert.equal(admission.status,'HUMAN_ADMITTED_29_OF_29');
assert.equal(admission.counts.admitted,29);assert.equal(admission.counts.runtimeUseAllowed,29);
assert.equal(admission.reviewEvidence.sha256,sha(reviewPath));
assert.equal(admission.reviewEvidence.reviewedAt,review.reviewedAt);
assert(admission.decisions.every(x=>x.decision==='ADMIT'&&x.admissionState==='HUMAN_ADMITTED_RULE_CLAIM'&&x.runtimeUseAllowed===true));
assert.equal(legacy.status,'CLAIM_BATCH_EXTRACTED_PENDING_HUMAN_ADMISSION_PRODUCTION_GATES_CLOSED');
assert.equal(legacy.claimBatches[0].humanAdmittedClaims,0,'historical extraction registry must remain unchanged');
assert.equal(registry.predecessorMutated,false);assert.equal(registry.claimBatches[0].humanAdmittedClaims,29);assert.equal(registry.claimBatches[0].runtimeUseAllowedClaims,29);
for(const v of Object.values(registry.engineeringGates))assert.equal(v,true);
for(const v of Object.values(registry.customerGates))assert.equal(v,false);
assert.deepEqual(new Set(ZIWEI_HUMAN_ADMITTED_CLAIM_IDS),new Set(claimIds));
assert.equal(assertZiweiSourceAdmission().state,'HUMAN_ADMITTED_29_OF_29');
assert.equal(acceptance.gates.ALL_29_ADMITTED,true);assert.equal(acceptance.gates.CUSTOMER_PUBLICATION_ALLOWED,false);
console.log('✓ ZIWEI Source-Claim Batch 001 human admission applied.');
console.log('  29/29 claims ADMIT; W3/W4 source gates and W5/W6 engineering start gates are open.');
console.log('  Historical extraction artifacts remain unchanged; customer publication remains closed.');
