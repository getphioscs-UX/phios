import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';

const BASELINE='ffb6e102bd3bccf02d2fb620df68561e98ba4b9f';
const PAGE='perspectives/personal/index.html';
const CSS='assets/customer-ui/surfaces/personal-reality-editorial-r5.css';
const JS='assets/customer-ui/js/surfaces/personal-reality.js';
const AUTH='content/professional/personal-reality/r5/authority/ppr-r5-editorial-successor-v1.json';
const CONTRACT='content/professional/personal-reality/r5/contracts/ppr-r5-editorial-successor-contract-v1.json';
const ACCEPT='content/professional/personal-reality/r5/acceptance/ppr-r5-editorial-acceptance-v1.json';
const read=p=>fs.readFileSync(p,'utf8');
const json=p=>JSON.parse(read(p));
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');

for(const p of [PAGE,CSS,JS,AUTH,CONTRACT,ACCEPT])assert(fs.existsSync(p),`PPR-R5 required file missing: ${p}`);
const authority=json(AUTH),contract=json(CONTRACT),acceptance=json(ACCEPT);
const page=read(PAGE),css=read(CSS);
assert.equal(authority.baselineCommit,BASELINE);
assert.equal(contract.baselineCommit,BASELINE);
assert.equal(acceptance.baselineCommit,BASELINE);
assert.equal(authority.status,'EDITORIAL_SUCCESSOR_IMPLEMENTED');
assert.equal(authority.predecessorPageSha256,'45ce923352d91dca8d7b3d3cc4dde47b70234ce6fad684b35b34b4e34d52d33e');
assert.equal(authority.sharedFileSuccessorProof[PAGE].successorSha256,sha(PAGE));
assert.equal(authority.addedFiles[CSS].sha256,sha(CSS));
assert.equal(authority.protectedFiles[JS].sha256,sha(JS));
assert.equal(authority.protectedFiles[JS].sha256,'34edad8d56cb00c1425674b2228eb9ba66ed9003521cc2d986a02f70269f5c2c');
for(const [k,v] of Object.entries(authority.boundaries))assert.equal(v,false,`PPR-R5 boundary drift: ${k}`);
assert.match(page,/data-ppr-r5-editorial="true"/);
for(const zone of ['hero','reality-compression','many-interfaces','method-taxonomy','governance'])assert.match(page,new RegExp(`data-ppr-r5-zone="${zone}"`),`PPR-R5 zone missing: ${zone}`);
for(const method of ['ecr','astrology','bazi','ziwei','numerology','human-design','iching','tarot'])assert.match(page,new RegExp(`data-ppr-r5-method="${method}"`),`PPR-R5 method taxonomy missing: ${method}`);
for(const phrase of ['REALITY COMPRESSION','ONE REALITY · MANY INTERFACES','Perspective ≠ Fact','Reality comparison'])assert(page.includes(phrase),`PPR-R5 editorial concept missing: ${phrase}`);
assert.match(page,/Human Design can be added as customer-supplied external context/);
assert.match(page,/href="\/perspectives\/iching\/"/);
assert.match(page,/href="\/perspectives\/tarot\/"/);
for(const method of ['ecr','astrology','bazi','numeric','ziwei'])assert.match(page,new RegExp(`data-method="${method}"`),`Existing product selector lost method: ${method}`);
assert.match(page,/data-cx-personal-form/);
assert.match(page,/data-ppr-r4-method-input-mount/);
assert.match(page,/data-cx-specialist-products/);
assert.match(page,/data-cx-cross-perspective/);
assert.match(page,/data-cx-reality-choice/);
assert.match(page,/personal-reality-editorial-r5\.css/);
assert(css.startsWith('/* PPR-R5 editorial successor: presentation only.'));
assert.match(css,/\[data-ppr-r5-editorial="true"\]/);
assert.doesNotMatch(css,/input\s*\{|textarea\s*\{|button\s*\{/);
assert.equal(contract.implementationBoundaries.mayChangeSpecialistRenderer,false);
assert.equal(contract.implementationBoundaries.mayChangeMethodInputSemantics,false);
assert.equal(contract.implementationBoundaries.mayCreateMethodMeaning,false);
assert.equal(acceptance.assertions.eightInterfaceCardsPresent,true);
assert.equal(acceptance.humanVisualAcceptanceStatus,'PENDING');

const currentSuccessorHelper=read('scripts/lib/ppr-c1-current-successor.mjs');
const cxR12r4Checker=read('scripts/check-cx-r12r4-personal-reading-experience.mjs');
assert.match(currentSuccessorHelper,/PPR_R5_EDITORIAL_SURFACE_SUCCESSOR/);
assert.match(cxR12r4Checker,/pprR5Editorial/);
console.log('✓ PPR-R5 editorial successor passed.');
console.log('  Reality Compression → Many Interfaces → Method Taxonomy → PHI OS Governance is present before the existing product selector.');
console.log('  8 interface cards are explicit; Human Design remains customer-supplied context; I Ching and Tarot remain separate question experiences.');
console.log('  PPR-R3 specialist renderer, PPR-R4 method inputs, calculations, projections and API semantics remain unchanged.');
