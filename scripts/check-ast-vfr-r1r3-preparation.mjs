import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import Ajv from 'ajv';
const base='content/professional/ast-full-production/publication/r1r3/';
const read=n=>JSON.parse(fs.readFileSync(base+n,'utf8'));
const hash=x=>crypto.createHash('sha256').update(x).digest('hex');
const request=read('english-generation-request.json'),audit=read('english-source-audit.json'),status=read('final-status.json');
for(const [file,digest] of Object.entries(read('source-preservation-audit.json').files))assert.equal(hash(fs.readFileSync(file)),digest,'Frozen source changed: '+file);
assert.equal(audit.existingFullEnglish.length,0);
assert.ok(audit.audited.length>0);
assert.equal(request.executionAuthorized,false);
assert.equal(request.automaticRetries,0);
assert.equal(request.maxProviderCalls,1);
assert.equal(request.immutableAuthoringPack.authoringPackDigest,request.sourceDigests.authoringPackDigest);
assert.equal(request.immutableAuthoringPack.canonicalProjectionDigest,request.sourceDigests.canonicalProjectionDigest);
assert.equal(request.sectionMap.length,10);
assert.equal(new Set(request.sectionMap.map(s=>s.sectionId)).size,10);
const sourceIds=request.acceptedChineseSource.map(b=>b.blockId),mapped=request.sectionMap.flatMap(s=>s.sourceBlocks.map(b=>b.blockId));
assert.deepEqual([...mapped].sort(),[...sourceIds].sort());
assert.equal(new Set(mapped).size,13);
new Ajv({strict:false}).compile(read('english-expected-schema.json'));
for(const key of ['englishProviderCalls','threeCallExperimentCalls','publicationCalls','diagramCalls','rerenderProviderCalls'])assert.equal(status[key],0);
assert.equal(status.state,'ENGLISH_GENERATION_READY');
assert.equal(status.enHumanAccept,false);
assert.equal(status.r1r3PageCount,null);
assert.equal(read('bilingual-publication-manuscript-v2.json').en,null);
assert.equal(read('english-cost-estimate.json').actualSpendUsd,0);
const html=fs.readFileSync('tools/review/AST-VFR-R1R3-ENGLISH-GENERATION-REVIEW.html','utf8');
for(const href of [...html.matchAll(/href="([^"]+)"/g)].map(m=>m[1]))assert.ok(fs.existsSync(new URL(href,new URL('file:///'+process.cwd().replaceAll('\\','/')+'/tools/review/AST-VFR-R1R3-ENGLISH-GENERATION-REVIEW.html'))),'Broken review link '+href);
fs.writeFileSync(base+'preparation-check-receipt.json',JSON.stringify({status:'PASS_PREPARATION_ONLY',frozenSources:'UNCHANGED',sourceBlocks:mapped.length,sections:10,providerCalls:0,bilingualPublication:'NOT_VERIFIED_PENDING_ENGLISH'},null,2)+'\n');
console.log('PASS AST-VFR-R1R3 English preparation; bilingual publication remains pending.');
