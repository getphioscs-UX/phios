import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>JSON.parse(fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8'));
const results=read('content/ecr-phi-card/review/ecr-phi-card-human-review-results-v1.json');
const admission=read('content/ecr-phi-card/admission/ecr-phi-card-customer-admission-v1.json');
assert.equal(results.requiredCaseCount,12);
assert.equal(results.results.length,12);
assert.equal(results.status,'HUMAN_ACCEPTED_12_OF_12');
assert.equal(results.acceptedCount,12);
assert.equal(results.rejectedCount,0);
assert.equal(results.pendingCount,0);
assert.ok(results.results.every(r=>r.decision==='ACCEPTED'));
assert.equal(results.reviewAuthority,'USER_HUMAN_ATTESTATION');
assert.equal(admission.status,'CUSTOMER_ADMITTED');
assert.equal(admission.customerAdmission,true);
assert.equal(admission.humanReview.accepted,12);
assert.equal(admission.humanReview.required,12);
assert.equal(admission.humanReview.decision,'ACCEPTED_12_OF_12');
assert.equal(admission.requirements.r2NetworkVerificationRequired,false);
