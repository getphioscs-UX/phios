import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
const text=p=>fs.readFileSync(p,'utf8').replace(/^\uFEFF/,'').replace(/\r\n?/g,'\n');
const read=p=>JSON.parse(text(p));
const sha256=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const contractPath='content/web-production/final-client-experience/contracts/part-k-final-freeze-contract-v1.json';
const acceptancePath='content/web-production/final-client-experience/acceptance/part-k-final-freeze-acceptance-v1.json';
const freezePath='content/web-production/final-client-experience/freeze/part-k-client-surface-final-freeze-v1.json';
const successorPath='content/web-production/final-client-experience/reconciliation/part-k-current-presentation-successor-v2.json';
for(const p of [contractPath,acceptancePath,freezePath,successorPath]) assert.ok(fs.existsSync(p),`PART_K_CURRENT_MISSING:${p}`);
const contract=read(contractPath), acceptance=read(acceptancePath), freeze=read(freezePath), successor=read(successorPath);
assert.equal(contract.work,'PART-K');
assert.equal(contract.status,'CLIENT_SURFACE_FINAL_MASTER_WORK_FREEZE_CONTRACT_ACTIVE');
assert.equal(acceptance.accepted,true);
assert.equal(freeze.successorRequiredForChange,true);
assert.equal(successor.status,'CURRENT_PART_K_PRESENTATION_FINGERPRINT_DECOUPLED_PREDECESSOR_AUTHORITY_PRESERVED');
assert.equal(successor.historicalFreeze.path,freezePath);
assert.equal(sha256(freezePath),successor.historicalFreeze.sha256,'PART_K_HISTORICAL_FREEZE_DRIFT');
assert.equal(successor.historicalFreeze.rewritten,false);
assert.equal(sha256(successor.historicalChecker.path),successor.historicalChecker.sha256,'PART_K_HISTORICAL_CHECKER_DRIFT');
assert.equal(successor.historicalChecker.rewritten,false);
assert.equal(successor.currentPolicy.presentationWholeFileFingerprint,false);
assert.equal(successor.currentPolicy.nonPresentationAuthorityFingerprintPreserved,true);
for(const v of Object.values(successor.boundaries)) assert.equal(v,false);
const presentation=new Map(successor.presentationSurfaces.map(x=>[x.path,x]));
for(const artifact of freeze.immutableArtifacts){
 assert.ok(fs.existsSync(artifact.path),`PART_K_CURRENT_ARTIFACT_MISSING:${artifact.path}`);
 const p=presentation.get(artifact.path);
 if(p){
  assert.equal(p.historicalSha256,artifact.sha256,`PART_K_PRESENTATION_HISTORY_MISMATCH:${artifact.path}`);
  assert.equal(p.wholeFileSha256Required,false,`PART_K_PRESENTATION_POLICY_DRIFT:${artifact.path}`);
  const src=text(artifact.path);
  assert.ok(src.trim().length>0,`PART_K_PRESENTATION_EMPTY:${artifact.path}`);
  for(const marker of p.requiredMarkers||[]) assert.ok(src.includes(marker),`PART_K_CURRENT_MARKER_MISSING:${artifact.path}:${marker}`);
 }else assert.equal(sha256(artifact.path),artifact.sha256,`PART_K_CURRENT_AUTHORITY_DRIFT:${artifact.path}`);
}
const bfr=read('content/web-production/acceptance/bfr-production-surface-acceptance-v1.json');
const hpc2=read('content/web/homepage/hpc2/acceptance/homepage-composition-acceptance-v2.json');
const cka=read('content/client/knowledge-ask/acceptance/cka-production-acceptance-v1.json');
assert.equal(bfr.status,contract.requiredPredecessorStates['BFR-H16']);
assert.equal(hpc2.status,contract.requiredPredecessorStates['HPC2-W14']);
assert.equal(cka.status,contract.requiredPredecessorStates['CKA-W33']);
const pkg=read('package.json');
assert.equal(pkg.scripts['check:part-k'],'node scripts/check-part-k-current.mjs');
assert.equal(pkg.scripts['check:part-k-historical'],'node scripts/check-part-k-final-freeze.mjs');
assert.equal(pkg.scripts['check:client-surface-final'],'npm run check:bfr-h && npm run check:part-j && npm run check:part-k');
console.log('✓ PART K current presentation successor passed.');
console.log('  Historical client-surface freeze remains evidence; current HTML/CSS presentation is semantic/hook-validated while non-presentation authority remains digest-bound.');
