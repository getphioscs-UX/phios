import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { runPublishedRetrieval, routePublishedQuery, rankPublishedCandidates, measurePublishedCoverage, sha } from './lib/knowledge-runtime/knr-package-a-v1.mjs';
const root = process.cwd();
const read = async file => JSON.parse(await fs.readFile(path.join(root, file), 'utf8'));
const contract = await read('content/knowledge/contracts/knr-package-a-routing-ranking-coverage-v1.json');
assert.equal(contract.policies.publishedOnly, true);
assert.equal(contract.policies.providerFree, true);
assert.equal(contract.prohibitedOperations.includes('generate_answer'), true);
const index = await read('content/knowledge/public/retrieval/published-retrieval-index.json');
const exactZh1 = await runPublishedRetrieval('人工智能如何从文明能力中形成？', 'zh-Hans');
const exactZh2 = await runPublishedRetrieval('人工智能如何从文明能力中形成？', 'zh-Hans');
assert.deepEqual(exactZh1, exactZh2);
assert.equal(exactZh1.ranking.results[0].nodeCode, 'KN-PREFACE-001');
assert.equal(exactZh1.ranking.results[0].locale, 'zh-Hans');
assert.equal(exactZh1.coverage.level, 'exact');
assert.equal(exactZh1.coverage.answerGenerationAllowed, false);
const exactEn = await runPublishedRetrieval('How Does Artificial Intelligence Emerge from Civilizational Capability?', 'en');
assert.equal(exactEn.ranking.results[0].nodeCode, 'KN-PREFACE-001');
assert.equal(exactEn.ranking.results[0].locale, 'en');
assert.equal(exactEn.coverage.level, 'exact');
const unsupported = await runPublishedRetrieval('anything', 'fr');
assert.equal(unsupported.route.routeCode, 'KNR-ROUTE-UNSUPPORTED-LOCALE');
assert.equal(unsupported.ranking.results.length, 0);
assert.equal(unsupported.coverage.level, 'none');
const none = await runPublishedRetrieval('quantum banana submarine', 'en');
assert.equal(none.ranking.results.length, 0);
assert.equal(none.coverage.supported, false);
const route = await routePublishedQuery({ query: 'artificial intelligence civilization', locale: 'en' });
assert(route.candidates.every(candidate => candidate.locale === 'en'));
const ranking = await rankPublishedCandidates(route);
const coverage = await measurePublishedCoverage(ranking);
assert.equal(coverage.answerGenerationAllowed, false);
const relationships = await read('content/knowledge/public/retrieval/relationships.json');
assert.equal(relationships.records.filter(record => !record.targetPublished).some(record => ranking.results.some(result => result.nodeCode === record.targetNodeCode)), false);
const freeze = await read('content/knowledge/production/freeze/knr-package-a-routing-ranking-coverage-v1.json');
assert.equal(freeze.status, 'KNR-PACKAGE-A-v1.0.0-Frozen');
assert.equal(freeze.sourceIndexDigest, index.indexDigest);
assert.equal(freeze.contractDigest, sha(contract));
console.log('✓ KNR-W3 published-only Query Routing passed.');
console.log('✓ KNR-W4 deterministic Ranking and stable tie-breaking passed.');
console.log('✓ KNR-W5 Coverage measurement and fail-closed unsupported queries passed.');
console.log('✓ No Provider, answer generation, unpublished promotion or canonical mutation passed.');
