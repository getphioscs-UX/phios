import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';

const text = path => fs.readFileSync(path, 'utf8');
const json = path => JSON.parse(text(path));
const sha256 = path => crypto.createHash('sha256').update(fs.readFileSync(path)).digest('hex');

const contract = json('content/web-production/pxr/contracts/pxr-public-experience-contract-v1.json');
const registry = json('content/web-production/pxr/registries/pxr-public-surface-registry-v1.json');
const publicAssets = json('content/registry/public-assets.json');
const h5Freeze = json('content/web-production/client-visual-consumption/freeze/part-h5-client-visual-consumption-freeze-v1.json');
const css = text('assets/css/pxr-public-experience.css');
const runtime = text('assets/js/public-experience/pxr-public-experience.js');
const i18n = text('assets/js/i18n.js');

assert.equal(contract.p1.heroPresentation, 'FULL_SURFACE');
assert.equal(contract.p1.autoIconRailPolicy, 'TRANSITIONAL_SUPPRESSED_PENDING_REPLACEMENT');
assert.equal(contract.p1.heroReplacementRequired, false);
assert.equal(contract.p1.iconReplacementSupportedWithoutSurfaceRewrite, true);
assert.equal(registry.heroPolicy.currentHeroAssetsPreserved, true);
assert.equal(registry.heroPolicy.detachedBottomFrameAllowed, false);
assert.equal(registry.iconPolicy.currentBatch, 'TRANSITIONAL_PENDING_REPLACEMENT');
assert.equal(registry.iconPolicy.autoGeneratedSupportRailsVisible, false);

// PART H.5 remains byte-immutable. PXR is presentation-only successor.
for (const artifact of h5Freeze.immutableArtifacts) {
  assert.equal(sha256(artifact.path), artifact.sha256, `PXR mutated frozen H.5 artifact: ${artifact.path}`);
}
assert.equal(contract.authorityBoundary.partH5FreezeMutated, false);
assert.equal(contract.authorityBoundary.secondVisualRegistryCreated, false);
assert.equal(contract.authorityBoundary.secondAssetResolverCreated, false);

assert.match(css, /\.client-visual-icon-rail[\s\S]*display:\s*none\s*!important/);
assert.match(css, /\.client-visual-masthead[\s\S]*--pxr-hero-max/);
assert.match(css, /height:\s*clamp\(28rem,\s*68vh,\s*52rem\)/);
assert.match(runtime, /resolvePublicAssetForWeb/);
assert.match(runtime, /pxr-visual-story/);
assert.match(i18n, /public-experience\/pxr-public-experience\.js/);
assert.doesNotMatch(runtime, /\.r2\.dev|pub-[a-z0-9]+/i);

const byCode = new Map(publicAssets.assets.map(asset => [asset.asset_code, asset]));
const storyCodes = new Set(registry.surfaces.flatMap(surface => (surface.storyFigures || []).map(item => item.assetCode)));
assert.ok(storyCodes.size >= 8, 'PXR core surfaces need meaningful Figure consumption');
for (const code of storyCodes) {
  const asset = byCode.get(code);
  assert.ok(asset, `PXR story figure missing from public-assets: ${code}`);
  assert.equal(asset.category, 'figure', `${code} is not a Figure`);
  assert.equal(asset.verification, 'verified-remote-head-get', `${code} is not remote verified`);
  assert.equal(asset.remote?.http_status, 200, `${code} lacks HTTP 200 evidence`);
}

// PXR must not promote currently unverified illustration/instruction material just to fill pages.
const activePXR = new Set(storyCodes);
for (const asset of publicAssets.assets.filter(asset => ['illustration', 'instruction'].includes(String(asset.category || '').toLowerCase()))) {
  if (asset.verification !== 'verified-remote-head-get') assert.equal(activePXR.has(asset.asset_code), false, `Unverified ${asset.category} silently promoted: ${asset.asset_code}`);
}

console.log(`✓ PXR-P1 Unified Visual Consumption passed: ${storyCodes.size} remote-verified Figure identities are consumed through the existing resolver; Hero assets are preserved and the transitional auto-icon rail is suppressed.`);
