import fs from 'node:fs';
import assert from 'node:assert/strict';
import * as rr from './lib/customer-report-runtime/report-runtime-v2.mjs';
import {buildPersonalEvidencePublicationProjection} from '../functions/profile/personal-evidence-publication-projection.js';
import {assemblePersonalEvidenceReport} from '../functions/profile/personal-evidence-report-adapter.js';
import {buildPersonalEvidencePublicationIr} from '../functions/profile/personal-evidence-publication-ir-adapter.js';
import {renderPersonalEvidenceDossier} from '../functions/canonical-presentation-runtime/personal-evidence-dossier-presentation.js';
import {buildPersonalEvidenceDossierProjection} from '../functions/profile/personal-evidence-dossier-projection.js';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const registry=read('content/runtime/customer-report-runtime/registries/canonical-report-section-registry-v2.json');
const extension=read('content/profile/successors/personal-evidence-r1/contracts/personal-evidence-rr-consumer-extension-v1.json');
const original=JSON.stringify(registry);
const view={schemaVersion:'PHI-OS-PROGRESSIVE-PROFILE-VIEW-v1',profileViewId:'W6-TEST',participantRef:'PERSON-A',asOfDate:'2026-10-04',semanticDigest:'a'.repeat(64),signalCards:[{signalRef:'SOURCE-A',sourceClass:'CUSTOMER_SELF_REPORT',domainId:'WORK',value:{rawScore:3},precisionBoundary:['SELF_REPORT_ONLY']}],boundaries:['No personality truth.']};
const visualProjection={participantRef:view.participantRef,figures:Array.from({length:9},(_,i)=>({pfig:`PFIG-${String(i+1).padStart(3,'0')}`,state:'UNKNOWN',data:{},evidenceRefs:[],customerLabel:{en:'Evidence unavailable','zh-Hans':'证据未知'}}))};
const projection=buildPersonalEvidencePublicationProjection({profileView:view,visualProjection,consentReferences:['CONSENT-A']});
const input={profileView:view,publicationProjection:projection,caseReference:'CASE-A',customerReference:'PERSON-A',assembledAt:'2026-10-04T00:00:00Z',rr,registry,extension};
const {report}=assemblePersonalEvidenceReport(input);
assert.equal(report.dataType,'REPORT_RECORD');
assert.equal(report.canonicalState,'APPROVED_UNRELEASED');
assert.equal(report.release,null);
assert.equal(report.sourceReferences[0].authority,'PROFILE_PPR');
assert.equal(JSON.stringify(registry),original);
assert.equal(assemblePersonalEvidenceReport(input).report.reportDigest,report.reportDigest);
assert.throws(()=>assemblePersonalEvidenceReport({...input,customerReference:'PERSON-B'}),/SUBJECT_MISMATCH/);
assert.throws(()=>assemblePersonalEvidenceReport({...input,publicationProjection:{...projection,consentReferences:[]}}),/CONSENT_REQUIRED/);
const ir=await buildPersonalEvidencePublicationIr({profileView:view,report,publicationProjection:projection});
assert.equal(ir.blocks[0].sourceRefs[0],'SOURCE-A');
assert.deepEqual(ir.blocks[0].semanticOperators,[]);
assert.equal(ir.blocks[0].snapshotLineage.reportReference,report.reportReference);
const dossier=buildPersonalEvidenceDossierProjection({visualProjection,participantRef:'PERSON-A'});
const html=renderPersonalEvidenceDossier({dossier,profileView:view,reviewPreview:true});
for(const id of ['P01','P02','P03','P04','P05',...Array.from({length:10},(_,i)=>`SEC-${String(i+1).padStart(2,'0')}`)])assert.equal(html.split(`data-pe-static="${id}"`).length-1,1,id);
for(let i=1;i<=9;i++)assert.equal(html.split(`data-pfig="PFIG-${String(i).padStart(3,'0')}"`).length-1,1);
assert.ok(html.includes('data-pe-sparse="true"'));
assert.ok(html.includes('PHI-OS-REPORT-PRINT-SHELL-V2'));
assert.ok(!html.includes('prf-visual-mvp__intro'));
assert.throws(()=>renderPersonalEvidenceDossier({dossier:projection.presentationPlan,profileView:view,report}),/RELEASE_REQUIRED/);
const released=rr.releaseCanonicalReport(report,{releaseReference:'TEST-RELEASE',releaseVersion:'1.0.0',channel:'HTML',time:'2026-10-04T01:00:00Z'});
const handoff=rr.buildCprReportHandoff(released);
assert.ok(renderPersonalEvidenceDossier({dossier,profileView:view,report:released,cprHandoff:handoff}).includes('pub-report'));
const sparse={...view,signalCards:[]};
const sp=buildPersonalEvidencePublicationProjection({profileView:sparse,visualProjection,consentReferences:['CONSENT-A']});
assert.equal(assemblePersonalEvidenceReport({...input,profileView:sparse,publicationProjection:sp}).report.sections.length,3);
console.log('PRD_W6_DOSSIER_RUNTIME = PASS (RR/IR V2/CPR/Print Shell reused; release tested with synthetic fixture only)');
