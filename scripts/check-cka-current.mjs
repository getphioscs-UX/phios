import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const text=p=>fs.readFileSync(p,'utf8');
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const succ=read('content/client/knowledge-ask/reconciliation/cka-w5-w17-current-successor-v1.json');
const partK=read('content/web-production/final-client-experience/reconciliation/part-k-current-presentation-successor-v2.json');
const authority=read('content/governance/current-authority-reconciliation/current-authority-successor-registry-v1.json');
const html=text('knowledge-search.html');
assert.equal(succ.status,'ACTIVE_ADDITIVE_VERSIONED_CLIENT_SUCCESSOR');
assert.equal(sha(succ.currentExtension.path),succ.currentExtension.sha256);
assert.match(html,/data-cka-root/);
assert.match(html,/Ask PHI OS/);
assert.match(html,/\/assets\/js\/pages\/knowledge-search-b\.js/);
assert.equal(succ.authorityBoundary.groundedAnswerOwner,'KAP');
assert.equal(succ.authorityBoundary.secondAnswerRuntimeCreated,false);
assert.equal(succ.authorityBoundary.secondRetrievalRuntimeCreated,false);
const surface=partK.presentationSurfaces.find(x=>x.path==='knowledge-search.html');
assert.ok(surface && surface.wholeFileSha256Required===false);
for (const marker of surface.requiredMarkers) assert.match(html,new RegExp(marker.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')));
const a=authority.authorities.find(x=>x.authorityId==='CLIENT_KNOWLEDGE_ASK_AUTHORITY');
assert.ok(a); assert.equal(a.currentFile,'content/client/knowledge-ask/reconciliation/cka-w5-w17-current-successor-v1.json');
console.log('✓ CKA current successor passed: semantic/client authority preserved; historical whole-file presentation fingerprint isolated.');
