import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import {parseHTML} from 'linkedom';
const html=readFileSync('perspectives/profile/index.html','utf8');
const css=readFileSync('assets/customer-ui/surfaces/profile-visitor-r1.css','utf8');
const js=readFileSync('assets/customer-ui/js/surfaces/profile-visitor-r1.js','utf8');
const codes=['QUICK_PROFILE','FULL_SELF_ASSESSMENT','REASONING_TASKS','IMPORT_EXTERNAL_RESULT','BIG_FIVE','CAREER_INTERESTS','FINANCIAL_CAPABILITY'];
const icons=['identity','expression','relationships','environment','growth','potential','quick','full','bigfive','career','financial','reasoning','external'];
const manifest=JSON.parse(readFileSync('content/production-closure/profile-visual-r1/ASSET-INTEGRATION-STATE.json','utf8'));
assert.equal(manifest.newVectorIcons.length,13,'Manifest must track each independent icon');
assert.ok(manifest.pending.some(x=>x.kind.startsWith('live_browser')),'Browser visual acceptance cannot be silently assumed');
assert.ok(manifest.criticalBoundaries.includes('No fake 4.2/5 dimensions'));

for(const icon of icons){
 const path='assets/icons/profile-r1/PHIOS-PROFILE-ICON-'+icon.toUpperCase()+'-v1.svg';
 assert.ok(existsSync(path),path+' missing');
 const source=readFileSync(path,'utf8');
 assert.match(source,/viewBox="0 0 64 64"/,'Missing scalable SVG viewBox');
 assert.ok(!/<script|onload=|foreignObject/i.test(source),'Invalid SVG payload');
}
const {document,window}=parseHTML(html);
const before=[...document.querySelectorAll('figure img')].map(img=>img.getAttribute('data-approved-visual')||img.getAttribute('src')||'').sort();
const heroBefore=document.querySelector('[data-vr2-role="HERO"] img')?.getAttribute('data-approved-visual');
const methodsBefore=[...document.querySelectorAll('[data-prf-mode]')].map(btn=>btn.dataset.prfMode).sort();
const inputCount=document.querySelectorAll('[data-prf-form] input,[data-prf-form] select,[data-prf-form] textarea').length;
assert.deepEqual(methodsBefore,codes.slice().sort());
const observer=window.MutationObserver||class{observe(){}};
runInNewContext(js,{document,window,MutationObserver:observer,queueMicrotask,console,URL,Event:window.Event});
document.dispatchEvent(new window.Event('DOMContentLoaded'));
assert.equal(document.body.dataset.prfVisitorR1,'ready','R1 controller did not initialize');
const mode=document.getElementById('profile-modes');
const hero=document.querySelector('.prf-main > .vr2-hero-surface');
const wb=document.querySelector('[data-prf-workbench]');
const results=document.querySelector('[data-prf-results]');
assert.equal(hero.nextElementSibling,mode,'Method selection must follow hero');
assert.equal(mode.nextElementSibling,wb,'User form must follow methods');
assert.equal(wb.nextElementSibling,results,'Results should follow form');
assert.equal(results.hidden,true,'Never invent a completed result');
assert.equal(wb.hidden,true,'Do not auto-submit/expand forms');
assert.equal(document.querySelectorAll('[data-prf-form] input,[data-prf-form] select,[data-prf-form] textarea').length,inputCount,'Inputs changed');
const actual=[...document.querySelectorAll('[data-prf-mode]')].map(x=>x.dataset.prfMode).sort();
assert.deepEqual(actual,codes.slice().sort(),'Method runtime IDs changed');
assert.equal(document.querySelectorAll('.prf-visitor-method-icon').length,7,'Missing entry icons');
const wheel=[...document.querySelectorAll('.prf-visitor-wheel__lens')];
assert.equal(wheel.length,6,'Wheel should have all six sectors');
assert.equal(wheel.filter(x=>x.getAttribute('aria-pressed')==='true').length,1,'Wheel selection invalid');
wheel[1].click();
assert.equal(wheel[1].getAttribute('aria-pressed'),'true','Wheel click must activate lens');
assert.ok(document.querySelector('.prf-visitor-wheel__center img')?.getAttribute('src')?.includes('PHIOS-LOGO-MARK-v1.png'),'Use official mark');
assert.ok(document.querySelector('[data-prf-account-save]'),'Account opt-in remains');
assert.equal(document.querySelector('[data-prf-account-save]').hasAttribute('checked'),false,'Never auto-save');
assert.ok(document.getElementById('prf-visitor-deeper')?.contains(document.querySelector('[data-profile-context-network]')));
const sample=document.getElementById('profile-example');
assert.ok(document.getElementById('prf-visitor-deeper').contains(sample),'All demos stay available on demand');
assert.ok(document.getElementById('prf-visitor-deeper').querySelector('img[data-approved-visual="PHIOS-FIGURE-PROFILE-SEVEN-ENTRY-MODES-v1.webp"]'));
const after=[...document.querySelectorAll('figure img')].map(img=>img.getAttribute('data-approved-visual')||img.getAttribute('src')||'').sort();
assert.deepEqual(after,before,'Existing Figures must be preserved exactly');
assert.equal(document.querySelector('[data-vr2-role="HERO"] img')?.getAttribute('data-approved-visual'),heroBefore,'Hero must remain');
assert.match(css,/prefers-reduced-motion/);
assert.match(css,/@media\(max-width:470px\)/);
assert.match(css,/object-fit:contain/);
assert.ok(!/localStorage|sessionStorage|fetch\(|method:\s*['"]POST['"]/.test(js),'Presentation layer may not access account/server storage');
assert.ok(!/4\.2\s*\/\s*5|3\.9\s*\/\s*5/.test(js),'Never ship fake demo scores');
assert.ok(html.includes('profile-visitor-r1.css')&&html.includes('profile-visitor-r1.js'),'Page lacks new modules');
console.log('PASS Profile Visitor R1 — seven native methods, 13 icons, six keyboard-compatible lenses, hero + figures, no new persistence; isolated DOM not live browser QA');
