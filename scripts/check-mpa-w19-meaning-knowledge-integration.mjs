import assert from 'node:assert/strict';
import { BASELINE, readJson } from './lib/method-production-activation/mpa-projection-integration-v1.mjs';
import { createProjectionFreezeRecord, resolveMeaningKnowledgeReferences } from '../functions/method-production-activation/projection-integration-runtime.js';

const contract = readJson('content/professional/method-production-activation/contracts/mpa-meaning-knowledge-integration-v1.json');
const projection = readJson('content/professional/method-production-activation/fixtures/mpa-w17-num-projection-freeze.valid.json');
const mappings = readJson('content/professional/canonical-meaning-runtime/registries/num-meaning-mapping-registry-v1.json');
const knowledgeMap = readJson('content/professional/canonical-meaning-runtime/registries/canonical-meaning-knowledge-map-v1.2.json');
const meaningQuery = readJson('content/professional/canonical-meaning-runtime/contracts/meaning-knowledge-query-contract-v1.json');
assert.equal(contract.work, 'MPA-W19');
assert.equal(contract.baselineCommit, BASELINE);
assert.equal(contract.authority.mpaRole, 'REFERENCE_ORCHESTRATION_ONLY');
assert.equal(contract.currentCompatibility.cmrProductionStatus, 'validation_only');
assert.equal(meaningQuery.status, 'validation_only');
assert.equal(contract.rules.mpaMayCreateMeaningCode, false);
assert.equal(contract.rules.mpaMayRewriteKnowledgeNode, false);
assert.equal(contract.rules.unpublishedKnowledgeExposureAllowed, false);
const freeze = await createProjectionFreezeRecord({projection, methodVersion:'0.1.0-candidate', calculationPolicyCode:'PHI_OS_NUMERIC_REDUCTION_V1', calculationPolicyVersion:'1.0.0', projectionPolicyCode:'MR-PROJECTION-EXT-NUMERIC-001', projectionPolicyVersion:'1.0.0'});
const ref = await resolveMeaningKnowledgeReferences({ projectionFreeze: freeze, meaningMappingRegistry: mappings, meaningKnowledgeMap: knowledgeMap });
assert.deepEqual(ref.meaningCodes, ['CM-NUMBER-ORIENTATION-NO08']);
assert.equal(ref.knowledge.length, 1);
assert.deepEqual(ref.knowledge[0].knowledgeReferences, ['KN-B1-P3-006','KN-B1-P3-007','KN-B1-P3-008','KN-B4-P14-004']);
assert.equal(ref.articleBodyStored, false);
assert.equal(ref.publishedFragmentTextStored, false);
assert.equal(ref.meaningCreated, false);
assert.equal(ref.knowledgeRewritten, false);
assert.equal(ref.interpretationCreated, false);
assert.equal(ref.validationReferenceOnly, true);
assert.match(ref.referenceDigest, /^[a-f0-9]{64}$/);
assert.equal(contract.productionEligibilityChanged, false);
console.log('✓ MPA-W19 Meaning / Knowledge Integration passed.');
console.log('  Projection can resolve governed Meaning and Knowledge references only; Meaning/Knowledge authority remains external and validation-only.');
