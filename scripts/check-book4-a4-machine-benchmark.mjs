import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildBook4A4Benchmark,BASELINE_COMMIT} from './lib/book4-a4-machine-benchmark.mjs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const stored=read('content/knowledge/knowledge-intelligence-r2/benchmarks/book4-a4-machine-retrieval-benchmark-v1.json');
const acceptance=read('content/knowledge/production-planning/acceptance/book4-a4-machine-acceptance-v1.json');
const audit=read('content/knowledge/production-planning/audits/book4-a4-machine-retrieval-audit-v1.json');
const authority=read('content/knowledge/contracts/book-4-machine-benchmark-authority-v1.json');
const manifest=read('content/knowledge/production-planning/production/book4-wave1/manifest-v1.json');
const prep=read('content/knowledge/production-planning/production/book4-wave1/pre-admission-contract-v1.json');
const active=read('content/knowledge/knowledge-intelligence-r2/registries/kir-r2-book-i-iii-source-admission-v1.json');
const recomputed=buildBook4A4Benchmark();
assert.deepEqual(stored,recomputed.benchmark,'stored A4 benchmark must equal a fresh execution of the existing KIR-R2 runtime');
assert.deepEqual(acceptance,recomputed.acceptance,'stored A4 acceptance must equal fresh benchmark acceptance');
assert.deepEqual(audit,recomputed.audit,'stored A4 audit must equal fresh benchmark audit');
assert.equal(stored.baselineCommit,BASELINE_COMMIT);
assert.equal(stored.machineAccepted,true,'A4 machine benchmark must pass all frozen thresholds');
assert.equal(stored.summary.book4PositiveCaseCount,250);
assert.equal(stored.summary.localeDistribution['zh-Hans'],125);
assert.equal(stored.summary.localeDistribution.en,125);
assert.equal(stored.summary.legacyControl.caseCount,100);
assert.ok(stored.summary.top1NodePrecision>=stored.thresholds.minimumTop1NodePrecision);
assert.ok(stored.summary.top5Recall>=stored.thresholds.minimumTop5Recall);
assert.ok(stored.summary.book4Top1Precision>=stored.thresholds.minimumBook4Top1Precision);
assert.ok(stored.summary.wrongBookTop1Rate<=stored.thresholds.maximumWrongBookTop1Rate);
assert.equal(stored.summary.sourceGroundingRate,1);
assert.equal(stored.summary.dedupIntegrityRate,1);
assert.ok(stored.summary.directAnswerPotentialRate>=stored.thresholds.minimumDirectAnswerPotentialRate);
assert.ok(stored.summary.byLocale['zh-Hans'].top5Recall>=stored.thresholds.minimumPerLocaleTop5Recall);
assert.ok(stored.summary.byLocale.en.top5Recall>=stored.thresholds.minimumPerLocaleTop5Recall);
assert.ok(stored.summary.byLocale['zh-Hans'].top1NodePrecision>=stored.thresholds.minimumPerLocaleTop1NodePrecision);
assert.ok(stored.summary.byLocale.en.top1NodePrecision>=stored.thresholds.minimumPerLocaleTop1NodePrecision);
assert.equal(stored.summary.legacyControl.expectedNodeTop5Recall,1);
assert.ok(stored.summary.legacyControl.book4HijackTop1Rate<=stored.thresholds.maximumLegacyBook4HijackTop1Rate);
assert.equal(stored.preAdmissionSimulation.book4ArticleSourcesSuppressed,true);
assert.equal(stored.boundaries.bookIVAdmitted,false);
assert.equal(stored.boundaries.publicationOpened,false);
assert.equal(stored.boundaries.humanAcceptanceClaimed,false);
assert.deepEqual(active.productionBooks,['BOOK-1','BOOK-2','BOOK-3']);
assert.equal(active.productionBooks.includes('BOOK-4'),false);
assert.equal(authority.work,'BOOK-IV-A4');
assert.equal(authority.status,'MACHINE_ACCEPTED_PRE_ADMISSION_A5_REQUIRED');
assert.equal(authority.nextWorkStep,'BOOK-IV-A5');
assert.equal(manifest.masterWork.a3Status,'COMPLETE');
assert.equal(manifest.masterWork.a4Status,'COMPLETE_MACHINE_ACCEPTED');
assert.ok(['READY_NOT_STARTED','REVIEW_READY_HUMAN_PENDING','HUMAN_ACCEPTED_26_OF_26'].includes(manifest.masterWork.a5Status));
assert.ok(['NOT_ADMITTED','PRODUCTION_ADMITTED'].includes(manifest.masterWork.a6Status));
assert.ok([false,true].includes(manifest.publication.bookIVAdmitted));
const seq=Object.fromEntries(prep.formalAdmissionSequence.map(x=>[x.workStep,x.status]));
assert.equal(seq['BOOK-IV-A3'],'COMPLETE');
assert.equal(seq['BOOK-IV-A4'],'COMPLETE_MACHINE_ACCEPTED');
assert.ok(['READY_NOT_STARTED','REVIEW_READY_HUMAN_PENDING','HUMAN_ACCEPTED_26_OF_26'].includes(seq['BOOK-IV-A5']));
assert.ok(['NOT_ADMITTED','PRODUCTION_ADMITTED'].includes(seq['BOOK-IV-A6']));
console.log(`✓ BOOK-IV-A4 Machine Benchmark passed: ${stored.summary.book4PositiveCaseCount} bilingual Book IV retrieval cases + ${stored.summary.legacyControl.caseCount} Book I–III no-hijack controls.`);
console.log(`✓ Recall ${(stored.summary.top5Recall*100).toFixed(1)}% · top-1 node precision ${(stored.summary.top1NodePrecision*100).toFixed(1)}% · Book IV top-1 precision ${(stored.summary.book4Top1Precision*100).toFixed(1)}% · wrong-book ${(stored.summary.wrongBookTop1Rate*100).toFixed(1)}%.`);
console.log(`✓ Source grounding ${(stored.summary.sourceGroundingRate*100).toFixed(0)}% · dedup ${(stored.summary.dedupIntegrityRate*100).toFixed(0)}% · direct-answer potential ${(stored.summary.directAnswerPotentialRate*100).toFixed(1)}% · legacy top-5 ${(stored.summary.legacyControl.expectedNodeTop5Recall*100).toFixed(0)}%.`);
console.log(`✓ ${stored.residualDiagnostics.top5Misses.length} top-5 misses and ${stored.residualDiagnostics.wrongBookTop1.length} wrong-book top-1 diagnostic are preserved for A5; passing A4 does not erase them.`);
console.log(`✓ BOOK-IV-A4 historical benchmark remains reproducible after later progression: A5=${manifest.masterWork.a5Status}, A6=${manifest.masterWork.a6Status}; Article publication remains separately gated.`);
