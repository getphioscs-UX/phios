import assert from 'node:assert/strict';
import fs from 'node:fs';
import {buildCustomerReadingIA} from '../functions/single-method-reading-r2/customer-reading-ia.js';
import {buildCustomerReadingLayout} from '../functions/single-method-reading-r2/customer-reading-layout.js';
import {buildSyntheticR2Narrative} from './smr-r2-w9-w11-test-support.mjs';

const contract=JSON.parse(fs.readFileSync('content/customer-experience-rebuild/r12r4b/smr-r2/contracts/smr-r2-reading-layout-contract-v1.json','utf8'));
const {narrative}=buildSyntheticR2Narrative();
const ia=buildCustomerReadingIA({narrativeIR:narrative});
const first=buildCustomerReadingLayout({readingIA:ia});
const second=buildCustomerReadingLayout({readingIA:ia});
assert.deepEqual(first,second);
assert.equal(first.schemaVersion,'PHI-OS-SMR-R2-READING-LAYOUT-PLAN-v1.0.0');
assert.ok(first.firstScreen.blockCount<=contract.firstScreenMaxBlocks);
assert.ok(first.firstScreen.themeCount<=contract.firstScreenMaxThemes);
assert.equal(first.firstScreen.technicalRefsIncluded,false);
assert.equal(first.firstScreen.blocks[0].slot,'READING_TITLE');
assert.equal(first.firstScreen.blocks.at(-1).slot,'EXPLORE_FULL_READING_CTA');
for(const forbidden of contract.firstScreen.forbidden)assert.ok(!first.firstScreen.blocks.some(block=>block.slot===forbidden));
assert.equal(first.desktop.contentWidthCssPx,contract.desktopContentWidth);
assert.equal(first.desktop.technicalDefaultCollapsed,true);
assert.equal(first.mobile.noHorizontalOverflow,true);
assert.equal(first.mobile.noNestedScroll,true);
assert.ok(first.mobile.minTapTargetCssPx>=44);
assert.equal(first.mobile.technicalPanelsCollapsed,true);
assert.equal(first.print.sectionAwareBreaks,true);
assert.equal(first.print.widowOrphanProtection,true);
assert.equal(first.print.clippedChartAllowed,false);
assert.equal(first.print.uiOnlyControlsIncluded,false);
assert.equal(first.technical.firstScreenAllowed,false);
assert.equal(first.boundary.layoutMeaningCreated,false);
assert.equal(first.boundary.webMobilePrintConsumeSameIA,true);
const level1Refs=new Set(ia.sections.filter(item=>item.disclosureLevel==='LEVEL_1_READING').flatMap(item=>item.items.map(x=>x.sourceRef)));
for(const block of first.firstScreen.blocks)for(const ref of block.sourceRefs)assert.ok(level1Refs.has(ref),`First screen consumed non-Level-1 source ${ref}`);
console.log('✓ CX-R12R4B SMR-R2 W10 layout passed: bounded first screen, single IA across web/mobile/print, collapsed technical detail, mobile safety and print break policy.');
