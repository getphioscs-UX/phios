import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { buildCanonicalBriefV2, serialize, digest } from './lib/knowledge-production/canonical-brief-v2.mjs';

const root=process.cwd();
const readJson=async p=>JSON.parse(await fs.readFile(path.join(root,p),'utf8'));
const schemaPath='content/knowledge/production/schemas/canonical-production-brief-v2.schema.json';
const manifestPath='content/knowledge/production/manifests/zh-hans-brief-export-manifest.json';
const freezePath='content/knowledge/production/freeze/pja-l10n-w2-zh-hans-brief-freeze-v1.json';
const testCommit='ad3dd14000000000000000000000000000000000';
const [schema,manifest,freeze]=await Promise.all([readJson(schemaPath),readJson(manifestPath),readJson(freezePath)]);
assert.equal(manifest.locale,'zh-Hans');
assert.equal(manifest.deterministic,true);
assert.deepEqual(manifest.allowedOperations,['read','project','validate','export','digest']);
for(const forbidden of ['write_registry','repair_data','generate_candidate','change_review','change_approval','publish']) assert(manifest.prohibitedOperations.includes(forbidden));
const first=await buildCanonicalBriefV2(root,'KN-PREFACE-001',{commit:testCommit});
const second=await buildCanonicalBriefV2(root,'KN-PREFACE-001',{commit:testCommit});
assert.equal(schema.properties.locale.const,'zh-Hans');
for (const key of schema.required) assert(Object.hasOwn(first,key),`SCHEMA_REQUIRED_FIELD_MISSING:${key}`);
assert.equal(first.briefType,schema.properties.briefType.const);
assert.equal(first.briefSchemaVersion,schema.properties.briefSchemaVersion.const);
assert.match(first.repositoryCommit,/^[a-f0-9]{40}$/);
assert.match(first.briefDigest,/^[a-f0-9]{64}$/);
assert.equal(serialize(first),serialize(second),'DETERMINISTIC_REBUILD_FAILED');
assert.equal(first.briefDigest,second.briefDigest);
const withoutDigest={...first}; delete withoutDigest.briefDigest;
assert.equal(first.briefDigest,digest(withoutDigest),'BRIEF_DIGEST_INVALID');
assert.equal(first.locale,'zh-Hans');
assert.equal(first.authority.review,'independent_human_review');
assert.equal(first.authority.approval,'independent_human_approval');
assert.equal(first.authority.publication,'independent_publication');
assert.equal(first.governance.registryMutationAllowed,false);
assert.equal(first.governance.publishedContentAllowed,false);
assert(!serialize(first).includes('generatedAt'));
assert.equal(freeze.status,'PJA-L10N-W2-v1.0.0-Frozen');
assert.equal(freeze.baselineCommit,'ad3dd14');
for(const [relative,expected] of Object.entries(freeze.digests)) {
  const actual=digest(await fs.readFile(path.join(root,relative)));
  assert.equal(actual,expected,`FREEZE_DIGEST_MISMATCH:${relative}`);
}
const tmp=await fs.mkdtemp(path.join(os.tmpdir(),'pja-l10n-w2-'));
await fs.writeFile(path.join(tmp,'brief.json'),serialize(first));
assert.equal(JSON.parse(await fs.readFile(path.join(tmp,'brief.json'),'utf8')).briefDigest,first.briefDigest);
console.log('✓ STEP55A Brief Schema passed.');
console.log('✓ STEP55B zh-Hans deterministic Brief Export Runtime passed.');
console.log('✓ STEP55C read-only Brief Checker passed.');
console.log('✓ STEP55D PJA-L10N-W2 Freeze digests passed.');
console.log(JSON.stringify({status:'passed',nodeCode:first.nodeCode,locale:first.locale,briefDigest:first.briefDigest,terminologyTerms:first.terminologyProjection.terms.length},null,2));
