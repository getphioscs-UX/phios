import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const BASE='82cc93f83c8eab1604b9fec02a6a1b86bfc56dd6';
const PLAN='content/knowledge/production-planning/plans/book3-w5-final-article-production-map-v1.json';
const VIS='content/knowledge/production-planning/visual-disposition/book3-all-w10-visual-closure-v1.json';
const PUB='content/knowledge/production-planning/publication/book3-zh-hans-publication-customer-integration-v1.json';
const RELEASE='content/knowledge/public/visual-article-release.json';
const plan=read(PLAN),vis=read(VIS),pub=read(PUB),release=read(RELEASE);
assert.equal(plan.articles.length,48);
assert.equal(vis.articleCount,48);
assert.equal(vis.successorBaselineCommit,BASE);
assert.deepEqual(vis.counts,{figureNotRequired:9,figureRecommendedNonBlocking:36,figureRequiredPublicationBlocking:3,requiredAssetsProduced:3,requiredAssetsHumanAccepted:3});
assert.equal(vis.publicationReadyByVisualGate,48);
assert.deepEqual(vis.publicationBlockedByVisualGate,[]);
assert.equal(pub.successorBaselineCommit,BASE);
assert.equal(pub.status,'PUBLICATION_CUSTOMER_PROJECTED_48_OF_48_ZH_HANS_COMPLETE');
assert.deepEqual(pub.counts,{plannedArticles:48,zhHansHumanAccepted:48,publicationAdmitted:48,customerProjected:48,blockedByVisualHumanGate:0,englishPublications:0});
assert.equal(pub.records.length,48);
assert.ok(pub.records.every(x=>x.publicationStatus==='PUBLISHED_CUSTOMER_PROJECTED'));
const releaseRows=release.records.filter(x=>x.source==='BOOK3-FINAL-ARTICLE-PRODUCTION'&&x.locale==='zh-Hans');
assert.equal(releaseRows.length,48);
assert.equal(new Set(releaseRows.map(x=>x.articlePlanId)).size,48);
assert.equal(new Set(releaseRows.map(x=>x.slug)).size,48);
assert.ok(releaseRows.every(x=>x.locale==='zh-Hans'&&x.status==='published'));
const planBy=new Map(plan.articles.map(x=>[x.articlePlanId,x]));
for(const r of pub.records){
  const p=planBy.get(r.articlePlanId); assert.ok(p);
  assert.deepEqual(r.coveredNodeCodes,p.nodeCodes);
  assert.equal(r.primaryNodeCode,p.primaryNodeCode);
  assert.ok(fs.existsSync(r.candidatePath));
  assert.equal(r.candidateSha256,sha(r.candidatePath));
  assert.equal(r.publicationStatus,'PUBLISHED_CUSTOMER_PROJECTED');
  assert.ok(fs.existsSync(r.publicArticlePath),`missing public payload ${r.articlePlanId}`);
  assert.equal(r.publicArticleSha256,sha(r.publicArticlePath));
  const a=read(r.publicArticlePath);
  assert.equal(a.nodeCode,p.primaryNodeCode);
  assert.deepEqual(a.coveredNodeCodes,p.nodeCodes);
  assert.equal(a.locale,'zh-Hans');
  assert.equal(a.publicationStatus,'published');
  assert.equal(a.publicationContext.publicationBookCode,'BOOK-3');
  assert.equal(a.publicationContext.publicationVolume,3);
  assert.equal(a.publicHref,r.href);
  assert.equal(a.slug,r.slug);
  assert.ok(fs.existsSync(`articles/${r.slug}.html`),`missing public route ${r.articlePlanId}`);
  assert.ok(!JSON.stringify(a).includes('reviewedCandidateSha256'));
  assert.ok(!JSON.stringify(a).includes('humanDecisionPath'));
  const allowed=new Set(['paragraph','lead','question','insight','mechanism','timeline','comparison','figure','transition','next_node']);
  const blocks=a.sections.flatMap(x=>x.blocks||[]);
  assert.ok(blocks.every(x=>allowed.has(x.type)),`${r.articlePlanId} unsupported public block type`);
  assert.ok(blocks.filter(x=>x.type==='paragraph').length>=5,`${r.articlePlanId} public body unexpectedly thin`);
}
for(const id of ['B3-ART-013','B3-ART-017','B3-ART-044']){
  const rr=pub.records.find(x=>x.articlePlanId===id); assert.ok(rr);
  const a=read(rr.publicArticlePath);
  assert.equal(a.visualAssets.length,1);
  assert.equal(a.sections[0].blocks.filter(x=>x.type==='figure').length,1);
  assert.equal(a.visualAssets[0].publicProjection,true);
}
const a44=pub.records.find(x=>x.articlePlanId==='B3-ART-044');
assert.equal(a44.visualGate,'SATISFIED_REQUIRED_VISUAL_HUMAN_ACCEPTED');
assert.ok(a44.visualHumanDecisionPath.endsWith('book3-b09-a44-visual-human-decision-v1.json'));
const renderer=fs.readFileSync('assets/js/knowledge/article-renderer.js','utf8');
for(const type of ['paragraph','question','insight','figure']) assert.ok(renderer.includes(`case '${type}'`));
const loader=fs.readFileSync('assets/js/knowledge/published-content.js','utf8');
assert.ok(loader.includes('visual-article-release.json'));
assert.ok(loader.includes('loadPublishedArticleBySlug'));
assert.equal(pub.boundaries.englishPublicationCreated,false);
assert.equal(pub.boundaries.legacyPublicationRegistryMutated,false);
